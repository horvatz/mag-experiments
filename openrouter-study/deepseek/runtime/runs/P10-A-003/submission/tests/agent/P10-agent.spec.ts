test('A04: multiple undo and redo preserve exact permutations without duplicates', async ({ page }) => {
  await mount(page)
  await click(page, 'Premakni web-02 gor')
  await click(page, 'Premakni web-04 gor')
  await click(page, 'Premakni web-06 gor')
  await expectIds(page, ['web-02', 'web-01', 'web-04', 'web-03', 'web-06', 'web-05', 'web-07', 'web-08'])
  await click(page, 'Razveljavi premik')
  await click(page, 'Razveljavi premik')
  await expectIds(page, ['web-02', 'web-01', 'web-03', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'])
  await expect(page.getByRole('status', { name: 'Zgodovina vrstnega reda' })).toHaveText('Razveljavitve: 1. Ponovitve: 2.')
  await click(page, 'Ponovi premik')
  await click(page, 'Ponovi premik')
  await expectIds(page, ['web-02', 'web-01', 'web-04', 'web-03', 'web-06', 'web-05', 'web-07', 'web-08'])
  await expect(page.getByRole('status', { name: 'Zgodovina vrstnega reda' })).toHaveText('Razveljavitve: 3. Ponovitve: 0.')
  const current = await ids(page)
  expect(new Set(current).size).toBe(current.length)
})

test('A05: new move after undo clears redo; reset is one undoable action that clears redo', async ({ page }) => {
  await mount(page)
  await click(page, 'Premakni web-02 gor')
  await click(page, 'Razveljavi premik')
  await expect(page.getByRole('button', { name: 'Ponovi premik', exact: true })).toBeEnabled()
  await click(page, 'Premakni web-03 gor')
  await expect(page.getByRole('button', { name: 'Ponovi premik', exact: true })).toBeDisabled()
  await expect(page.getByRole('status', { name: 'Zgodovina vrstnega reda' })).toHaveText('Razveljavitve: 1. Ponovitve: 0.')
  await click(page, 'Razveljavi premik')
  await click(page, 'Premakni web-04 gor')
  await click(page, 'Premakni web-05 gor')
  await click(page, 'Razveljavi premik')
  await expect(page.getByRole('button', { name: 'Ponovi premik', exact: true })).toBeEnabled()
  await click(page, 'Začetni vrstni red')
  await expectIds(page, webIds())
  await expect(page.getByRole('button', { name: 'Začetni vrstni red', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Ponovi premik', exact: true })).toBeDisabled()
  await expect(page.getByRole('status', { name: 'Zgodovina vrstnega reda' })).toHaveText('Razveljavitve: 2. Ponovitve: 0.')
  await click(page, 'Razveljavi premik')
  await expect(page.getByLabel('Mesto opravila web-04', { exact: true })).toHaveText('3')
})

test('A06: undo history keeps at most 20 permutations and redo restores all of them', async ({ page }) => {
  await mount(page)
  for (let step = 0; step < 7; step += 1) await click(page, 'Premakni web-08 gor')
  for (let step = 0; step < 7; step += 1) await click(page, 'Premakni web-08 dol')
  for (let step = 0; step < 6; step += 1) await click(page, 'Premakni web-07 gor')
  await click(page, 'Premakni web-01 dol')
  await expectIds(page, ['web-07', 'web-02', 'web-01', 'web-03', 'web-04', 'web-05', 'web-06', 'web-08'])
  for (let step = 0; step < 20; step += 1) await click(page, 'Razveljavi premik')
  await expect(page.getByRole('button', { name: 'Razveljavi premik', exact: true })).toBeDisabled()
  await expect(page.getByRole('status', { name: 'Zgodovina vrstnega reda' })).toHaveText('Razveljavitve: 0. Ponovitve: 20.')
  await expectIds(page, ['web-01', 'web-02', 'web-03', 'web-04', 'web-05', 'web-06', 'web-08', 'web-07'])
  for (let step = 0; step < 20; step += 1) await click(page, 'Ponovi premik')
  await expectIds(page, ['web-07', 'web-02', 'web-01', 'web-03', 'web-04', 'web-05', 'web-06', 'web-08'])
  await expect(page.getByRole('status', { name: 'Zgodovina vrstnega reda' })).toHaveText('Razveljavitve: 20. Ponovitve: 0.')
})

