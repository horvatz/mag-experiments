import { test, expect, mount, expectIds, ids, select, click, board, table, details, project, summary, readonly, makeTask, webIds } from '../development/helpers.ts'

const status = (page: Parameters<typeof mount>[0]) => page.getByRole('status', { name: 'Stanje straničenja' })
const badge = (page: Parameters<typeof mount>[0]) => page.locator('.count-badge')
const columnCounts = (page: Parameters<typeof mount>[0]) => page.locator('.column-count').evaluateAll((nodes) => nodes.map((node) => Number(node.textContent)))

test('R01: privzeto all/all, vsa opravila v izvornem vrstnem redu', async ({ page }) => {
  await mount(page)
  await expect(page.getByRole('combobox', { name: 'Velikost strani', exact: true })).toHaveValue('all')
  await expect(page.getByRole('combobox', { name: 'Filter strani', exact: true })).toHaveValue('all')
  await expectIds(page, webIds())
  await expect(status(page)).toHaveText('Stran 1 od 1. Prikazano 1–8 od 8.')
  await expect(badge(page)).toHaveText('8')
  await expect(page.getByRole('button', { name: 'Prva stran', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Zadnja stran', exact: true })).toBeDisabled()
})

test('R02: odseki 2/5/10 brez izgube ali podvajanja', async ({ page }) => {
  await mount(page)
  await select(page, 'Velikost strani', '2')
  const collected: string[] = []
  for (let index = 0; index < 4; index += 1) {
    const current = (await ids(page)).filter((id): id is string => id !== null)
    expect(current.length).toBeLessThanOrEqual(2)
    collected.push(...current)
    if (index < 3) await click(page, 'Naslednja stran')
  }
  expect(collected).toEqual(webIds())
  expect(new Set(collected).size).toBe(collected.length)
  await select(page, 'Velikost strani', '5')
  await expectIds(page, webIds().slice(0, 5))
  await click(page, 'Zadnja stran')
  await expectIds(page, webIds().slice(5))
  await expect(status(page)).toHaveText('Stran 2 od 2. Prikazano 6–8 od 8.')
  await select(page, 'Velikost strani', '10')
  await expectIds(page, webIds())
  await expect(status(page)).toHaveText('Stran 1 od 1. Prikazano 1–8 od 8.')
})

test('R02/R04: velikost 10 na enajstih opravilih, krajša zadnja stran', async ({ page }) => {
  const records = Array.from({ length: 11 }, (_, index) => makeTask(`custom-${String(index + 1).padStart(2, '0')}`))
  await mount(page, records)
  await select(page, 'Velikost strani', '10')
  await expectIds(page, records.slice(0, 10).map((task) => task.id))
  await click(page, 'Naslednja stran')
  await expectIds(page, records.slice(10).map((task) => task.id))
  await expect(status(page)).toHaveText('Stran 2 od 2. Prikazano 11–11 od 11.')
})

test('R03: navigacija in onemogočeni gumbi na robovih', async ({ page }) => {
  await mount(page)
  await select(page, 'Velikost strani', '2')
  await expectIds(page, ['web-01', 'web-02'])
  await expect(page.getByRole('button', { name: 'Prva stran', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Prejšnja stran', exact: true })).toBeDisabled()
  await click(page, 'Naslednja stran')
  await expectIds(page, ['web-03', 'web-04'])
  await click(page, 'Naslednja stran')
  await expectIds(page, ['web-05', 'web-06'])
  await click(page, 'Zadnja stran')
  await expectIds(page, ['web-07', 'web-08'])
  await expect(page.getByRole('button', { name: 'Naslednja stran', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Zadnja stran', exact: true })).toBeDisabled()
  await click(page, 'Prejšnja stran')
  await expectIds(page, ['web-05', 'web-06'])
  await click(page, 'Prva stran')
  await expectIds(page, ['web-01', 'web-02'])
  await page.getByRole('button', { name: 'Prejšnja stran', exact: true }).evaluate((element) => (element as HTMLButtonElement).click())
  await expectIds(page, ['web-01', 'web-02'])
  await expect(status(page)).toHaveText('Stran 1 od 4. Prikazano 1–2 od 8.')
})

