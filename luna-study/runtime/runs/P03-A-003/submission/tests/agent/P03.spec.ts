import { test, expect, mount, expectIds, select, board, table, project, examples, summary } from '../development/helpers.ts'

test('P03: normalized all-word literal search reads every searchable field', async ({ page }) => {
  await mount(page)
  const search = page.getByRole('searchbox', { name: 'Išči opravila' })
  await search.fill('koncni CAS')
  await expectIds(page, ['web-01'])
  await search.fill('=SUM(A1)')
  await expectIds(page, ['web-07'])
  await search.fill('neobstaja')
  await expectIds(page, [])
  await board(page)
  await expect(page.getByText('Ni zadetkov.', { exact: true })).toBeVisible()
  await expectIds(page, [])
})

test('P03: people include filtered-out tasks, project changes reset controls, and board keeps matches', async ({ page }) => {
  await mount(page, examples)
  await page.getByRole('searchbox', { name: 'Išči opravila' }).fill('citat')
  const people = page.getByRole('combobox', { name: 'Filter odgovorne osebe' })
  await expect(people.locator('option')).toHaveCount(6)
  await select(page, 'Filter odgovorne osebe', 'Živa Kovač')
  await expectIds(page, ['web-06'])
  await board(page)
  await expectIds(page, ['web-06'])
  await project(page, 'launch')
  await expect(page.getByRole('searchbox', { name: 'Išči opravila' })).toHaveValue('')
  await expect(page.getByRole('combobox', { name: 'Filter stanja' })).toHaveValue('all')
  await expect(page.getByRole('combobox', { name: 'Filter odgovorne osebe' })).toHaveValue('all')
  await expect(page.getByRole('combobox', { name: 'Filter odgovorne osebe' }).locator('option')).toHaveCount(3)
  await expectIds(page, ['launch-01', 'launch-02'])
  await table(page)
})

test('P03: filtered counts, clear, and refresh defaults', async ({ page }) => {
  await mount(page)
  await select(page, 'Filter stanja', 'done')
  await select(page, 'Filter odgovorne osebe', 'Živa Kovač')
  await page.getByRole('searchbox', { name: 'Išči opravila' }).fill('citat')
  await expectIds(page, ['web-06'])
  await expect(page.getByRole('status', { name: 'Rezultati filtriranja' })).toHaveText('Prikazano: 1 od 8.')
  await summary(page, [0, 0, 1])
  await page.reload()
  await expect(page.getByRole('searchbox', { name: 'Išči opravila' })).toHaveValue('')
  await expect(page.getByRole('combobox', { name: 'Filter stanja' })).toHaveValue('all')
  await expect(page.getByRole('combobox', { name: 'Filter odgovorne osebe' })).toHaveValue('all')
  await expectIds(page, ['web-01', 'web-02', 'web-03', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'])
  await select(page, 'Filter stanja', 'done')
  await select(page, 'Filter odgovorne osebe', 'Ana Novak')
  await page.getByRole('searchbox', { name: 'Išči opravila' }).fill('neobstaja')
  await expectIds(page, [])
  await page.getByRole('button', { name: 'Počisti filtre' }).click()
  await expect(page.getByRole('searchbox', { name: 'Išči opravila' })).toHaveValue('')
  await expect(page.getByRole('combobox', { name: 'Filter stanja' })).toHaveValue('all')
  await expect(page.getByRole('combobox', { name: 'Filter odgovorne osebe' })).toHaveValue('all')
  await expectIds(page, ['web-01', 'web-02', 'web-03', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'])
})

test('P03: empty project retains empty state and zero results', async ({ page }) => {
  await mount(page, examples.filter((task) => task.projectId === 'launch'))
  await expect(page.getByRole('status', { name: 'Rezultati filtriranja' })).toHaveText('Prikazano: 0 od 0.')
  await expect(page.getByRole('heading', { name: 'V tem projektu še ni opravil' })).toBeVisible()
  await board(page)
  await expect(page.getByRole('region', { name: 'Tabla opravil' })).toBeVisible()
})
