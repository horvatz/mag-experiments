test("A04: neveljaven zapis pomeni prazno množico in se ne prepiše", async ({ page }) => {
  const invalid = ["ni json", "[]", JSON.stringify({ version: 2, ids: ["web-02"] }), JSON.stringify({ version: 1 }), JSON.stringify({ version: 1, ids: "web-02" }), JSON.stringify({ version: 1, ids: ["web-02", 5] })]
  for (const raw of invalid) {
    await seed(page, raw)
    await mount(page)
    await expect(page.getByRole("button", { name: /^Priljubljeno opravilo / }).first()).toHaveAttribute("aria-pressed", "false")
    await expect.poll(() => stored(page)).toBe(raw)
  }
  await seed(page, null)
  await mount(page)
  await expect(counter(page)).toHaveText("Priljubljeno: 0 od 8.")
  await expect.poll(() => stored(page)).toBe(null)
})

