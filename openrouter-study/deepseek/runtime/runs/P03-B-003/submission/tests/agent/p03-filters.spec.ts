import { test, expect, mount, expectIds, webIds, select, board, table, click, readonly, summary, columnIds, project, makeTask } from '../development/helpers.ts'

const search = (page: Parameters<typeof mount>[0]) => page.getByRole('searchbox', { name: 'Išči opravila' })
const statusText = (page: Parameters<typeof mount>[0]) => page.getByRole('status', { name: 'Rezultati filtriranja' })
const ids = (page: Parameters<typeof mount>[0]) => page.locator('[data-task-id]').evaluateAll((nodes) => nodes.map((node) => node.getAttribute('data-task-id')))

test('R01/R09: defaults show every task of the project in source order', async ({ page }) => {
  await mount(page)
  await expect(search(page)).toHaveValue('')
  await expect(page.getByRole('combobox', { name: 'Filter stanja' })).toHaveValue('all')
  await expect(page.getByRole('combobox', { name: 'Filter odgovorne osebe' })).toHaveValue('all')
  await expect(statusText(page)).toHaveText('Prikazano: 8 od 8.')
  await expectIds(page, webIds())
  await summary(page, [4, 2, 2])
})

test('R08: refresh starts with defaults and no filter state is persisted', async ({ page }) => {
  await mount(page)
  await search(page).fill('pregled')
  await select(page, 'Filter stanja', 'done')
  await expectIds(page, ['web-03'])
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Spletna prenova', exact: true })).toBeVisible()
  await expect(search(page)).toHaveValue('')
  await expect(page.getByRole('combobox', { name: 'Filter stanja' })).toHaveValue('all')
  await expect(page.getByRole('combobox', { name: 'Filter odgovorne osebe' })).toHaveValue('all')
  await expectIds(page, webIds())
  expect(new URL(page.url()).search).toBe('')
  expect(await page.evaluate(() => Object.keys(localStorage))).toEqual([])
  expect(await page.evaluate(() => Object.keys(sessionStorage))).toEqual([])
  expect(await page.evaluate(() => document.cookie)).toBe('')
})

