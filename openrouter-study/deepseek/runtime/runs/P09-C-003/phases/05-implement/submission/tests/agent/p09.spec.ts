test("R11: reset, empty results and the result counter", async ({ page }) => {
  await mount(page)
  await expect(counter(page)).toHaveText("Prikazano: 8 od 8.")
  await select(page, "Stanje v povezavi", "done")
  await click(page, "Uporabi pogled")
  await expect(counter(page)).toHaveText("Prikazano: 2 od 8.")
  await search(page).fill("neobstojece")
  await click(page, "Uporabi pogled")
  await expect(page.getByRole("heading", { name: "Ni zadetkov." })).toBeVisible()
  await expect(counter(page)).toHaveText("Prikazano: 0 od 8.")
  await click(page, "Ponastavi pogled")
  await expectIds(page, webIds())
  await expect.poll(() => hash(page)).toBe("#/projects/web")
  await expect(counter(page)).toHaveText("Prikazano: 8 od 8.")
  await board(page)
  await select(page, "Stanje v povezavi", "done")
  await click(page, "Uporabi pogled")
  await click(page, "Ponastavi pogled")
  await expect(page.getByRole("region", { name: "Tabla opravil" })).toBeVisible()
  await expect.poll(() => hash(page)).toBe("#/projects/web?view=board")
})

test("R11: counter and order with custom data sets", async ({ page }) => {
  const many = Array.from({ length: 12 }, (_, index) => makeTask(`m-${String(index + 1).padStart(2, "0")}`, { title: "Enako" }))
  await mount(page, many, "#/projects/web?order=title-asc")
  await expect(counter(page)).toHaveText("Prikazano: 12 od 12.")
  await expectIds(page, many.map((task) => task.id))
  await mount(page, [makeTask("solo", { title: "Edino opravilo" })], "#/projects/web?q=edino")
  await page.reload()
  await expectIds(page, ["solo"])
  await mount(page, [], "#/projects/web?q=x")
  await page.reload()
  await expect(page.getByRole("heading", { name: "V tem projektu še ni opravil" })).toBeVisible()
  await expect(counter(page)).toHaveText("Prikazano: 0 od 0.")
})

