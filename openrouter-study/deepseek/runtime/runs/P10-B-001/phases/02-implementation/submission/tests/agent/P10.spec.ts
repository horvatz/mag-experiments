test('R10: views and details keep state, project switch and reload reset it', async ({ page }) => {
  await mount(page)
  await click(page, 'Premakni web-02 gor')
  await board(page)
  await expect(page.getByLabel('Mesto opravila web-02', { exact: true })).toHaveText('1')
  await table(page)
  await details(page, 'web-02')
  await expect(page.getByLabel('Mesto opravila web-02', { exact: true })).toHaveText('1')
  await expect(page.getByRole('status', { name: 'Zgodovina vrstnega reda', exact: true })).toHaveText('Razveljavitve: 1. Ponovitve: 0.')
  await project(page, 'launch')
  await project(page, 'web')
  await expectIds(page, webIds())
  await expect(page.getByRole('status', { name: 'Zgodovina vrstnega reda', exact: true })).toHaveText('Razveljavitve: 0. Ponovitve: 0.')
  await click(page, 'Premakni web-02 gor')
  await page.reload()
  await expectIds(page, webIds())
  await expect(page.getByRole('status', { name: 'Zgodovina vrstnega reda', exact: true })).toHaveText('Razveljavitve: 0. Ponovitve: 0.')
})

