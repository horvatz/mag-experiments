import { test, expect, mount, expectIds, webIds, select, click, details } from '../development/helpers.ts'

test('direct URL state filters by a literal normalized phrase and tolerates unknown query values', async ({ page }) => {
  const hash = '#/projects/web?view=board&q=CAS%20za%20PREGLED&status=invalid&status=done&order=title-desc&extra=ignored'
  await mount(page, undefined, hash)
  await expect(page.getByRole('searchbox', { name: 'Iskanje v povezavi' })).toHaveValue('CAS za PREGLED')
  await expect(page.getByRole('combobox', { name: 'Stanje v povezavi' })).toHaveValue('all')
  await expect(page.getByRole('button', { name: 'Tabla', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expectIds(page, ['web-01'])
  await expect(page.getByRole('status', { name: 'Rezultati povezave' })).toHaveText('Prikazano: 1 od 8.')
  expect(new URL(page.url()).hash).toBe(hash)
  await details(page, 'web-01')
  expect(new URL(page.url()).hash).toContain('view=board')
  expect(new URL(page.url()).hash).toContain('q=CAS+za+PREGLED')
})

test('draft filters apply together, back and forward restore them, and reset preserves the view', async ({ page }) => {
  const writes = await mount(page)
  await select(page, 'Stanje v povezavi', 'done')
  await select(page, 'Vrstni red v povezavi', 'title-desc')
  await expectIds(page, webIds())
  await click(page, 'Uporabi pogled')
  await expectIds(page, ['web-06', 'web-03'])
  await page.getByRole('searchbox', { name: 'Iskanje v povezavi' }).fill('pregled')
  await click(page, 'Uporabi pogled')
  await expectIds(page, ['web-03'])
  await page.goBack()
  await expectIds(page, ['web-06', 'web-03'])
  await expect(page.getByRole('searchbox', { name: 'Iskanje v povezavi' })).toHaveValue('')
  await page.goForward()
  await expectIds(page, ['web-03'])
  await page.getByRole('button', { name: 'Tabla', exact: true }).click()
  await expectIds(page, ['web-03'])
  await select(page, 'Stanje v povezavi', 'todo')
  await click(page, 'Ponastavi pogled')
  await expectIds(page, webIds(), false)
  expect(new URL(page.url()).hash).toContain('view=board')
  expect(new URLSearchParams(new URL(page.url()).hash.split('?')[1]).has('status')).toBe(false)
  await expect(page.getByRole('searchbox', { name: 'Iskanje v povezavi' })).toHaveValue('')
  expect(writes).toEqual([])
})

test('navigation between projects resets filters but retains view and draft edits do not leak', async ({ page }) => {
  const hash = '#/projects/web?view=board&status=done'
  await mount(page, undefined, hash)
  await expectIds(page, ['web-03', 'web-06'])
  await select(page, 'Stanje v povezavi', 'todo')
  await page.getByRole('navigation', { name: 'Projekti' }).getByRole('link', { name: 'Jesenska kampanja' }).click()
  await expect(page.getByRole('combobox', { name: 'Stanje v povezavi' })).toHaveValue('all')
  await expect(page.getByRole('button', { name: 'Tabla', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expectIds(page, ['launch-01', 'launch-02'], false)
  expect(new URL(page.url()).hash).toBe('#/projects/launch?view=board')
})

test('an empty project reports no results in the table and board', async ({ page }) => {
  const writes = await mount(page, [], '#/projects/web')
  await expect(page.getByRole('heading', { name: 'V tem projektu še ni opravil' })).toBeVisible()
  await expect(page.getByText('Ni zadetkov.', { exact: true })).toBeVisible()
  await expect(page.getByRole('status', { name: 'Rezultati povezave' })).toHaveText('Prikazano: 0 od 0.')
  await page.getByRole('button', { name: 'Tabla', exact: true }).click()
  await expect(page.getByText('Ni zadetkov.', { exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Tabla opravil' })).toBeVisible()
  expect(writes).toEqual([])
})
