import type { Page } from '@playwright/test'
import { test, expect, mount, expectIds, webIds, click, board, table, readonly, details, project, ids, makeTask } from '../development/helpers.ts'

const columnIds = (page: Page, column: string) => page.locator(`${column} [data-task-id]`).evaluateAll((nodes) => nodes.map((node) => node.getAttribute('data-task-id')))

test('A01: initial order equals received order, global places 1..N, fields unchanged', async ({ page }) => {
  const writes = await mount(page)
  await expectIds(page, webIds())
  for (const [index, id] of webIds().entries()) {
    await expect(page.getByLabel(`Mesto opravila ${id}`, { exact: true })).toHaveText(String(index + 1))
  }
  await expect(page.locator('[aria-label^="Mesto opravila"]')).toHaveCount(8)
  await expect(page.getByText('Pregled vsebine', { exact: true })).toHaveCount(2)
  const row = page.locator('[data-task-id="web-01"]')
  await expect(row.getByText('V delu', { exact: true })).toBeVisible()
  await expect(row.getByText('Ana Novak', { exact: true })).toBeVisible()
  await expect(row.locator('time')).toHaveAttribute('datetime', '2026-09-18')
  await readonly(page, writes)
})

