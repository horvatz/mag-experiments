import { choose, controls, expect, labels, onlyStatuses, presentation, reset, snapshot, summary, test } from '../development/helpers.ts'
import type { Page } from '@playwright/test'

async function capture(page: Page, name: string) {
  await page.evaluate(() => {
    if (document.activeElement instanceof HTMLElement) document.activeElement.blur()
    window.scrollTo(0, 0)
  })
  await page.screenshot({ path: `docs/agent/${name}.png`, fullPage: true, animations: 'disabled' })
}

for (const viewport of [{ width: 1440, height: 960 }, { width: 320, height: 740 }]) {
  test.describe(`P02 ${viewport.width}px`, () => {
    test.use({ viewport })
    test.beforeEach(async ({ request }) => { await reset(request) })

    test('A01: izbor po ID, vmesno stanje, oba pogleda in ponastavitev projekta brez zapisov', async ({ page, request, transport }) => {
      const before = await snapshot(request)
      await page.goto('/')
      const form = controls(page)
      await expect(form.count).toHaveText('Izbrano: 0')
      await expect(form.target).toHaveValue('')
      await expect(form.apply).toBeDisabled()
      await expect(form.all).not.toBeChecked()
      await form.target.selectOption('in_progress')
      await expect(form.apply).toBeDisabled()
      await form.item('web-01').check()
      await expect(form.item('web-02')).not.toBeChecked()
      await expect(page.getByRole('dialog')).toHaveCount(0)
      await expect(form.all).toHaveJSProperty('indeterminate', true)
      await expect(form.count).toHaveText('Izbrano: 1')
      await expect(form.apply).toBeEnabled()
      await presentation(page, before.tasks, 'web', 'table')
      if (viewport.width === 1440) await capture(page, 'table-desktop')
      await page.getByRole('button', { name: 'Tabla', exact: true }).click()
      await expect(page.getByRole('region', { name: 'Tabla opravil', exact: true })).toBeVisible()
      await expect(form.item('web-01')).toBeChecked()
      await expect(form.target).toHaveValue('in_progress')
      if (viewport.width === 1440) await capture(page, 'board-desktop')
      await form.item('web-02').focus()
      await page.keyboard.press('Space')
      await expect(form.item('web-02')).toBeChecked()
      await expect(form.item('web-01')).toBeChecked()
      await expect(page.getByRole('dialog')).toHaveCount(0)
      await expect(form.count).toHaveText('Izbrano: 2')
      await form.all.click()
      await expect(form.all).toBeChecked()
      await expect(form.all).toHaveJSProperty('indeterminate', false)
      await expect(form.count).toHaveText('Izbrano: 3')
      await form.all.click()
      await expect(form.count).toHaveText('Izbrano: 0')
      await expect(form.all).toHaveJSProperty('indeterminate', false)
      await expect(form.apply).toBeDisabled()
      await form.item('web-02').check()
      await page.getByRole('button', { name: 'Preglednica', exact: true }).click()
      await expect(form.item('web-02')).toBeChecked()
      await expect(form.item('web-01')).not.toBeChecked()
      await form.clear.click()
      await expect(form.count).toHaveText('Izbrano: 0')
      await expect(form.target).toHaveValue('')
      await form.item('web-01').check()
      await expect(form.apply).toBeDisabled()
      await form.target.selectOption('todo')
      await page.getByRole('navigation').getByRole('link', { name: 'Jesenska kampanja' }).click()
      await expect(form.item('launch-01')).not.toBeChecked()
      await expect(form.count).toHaveText('Izbrano: 0')
      await expect(form.target).toHaveValue('')
      await page.getByRole('navigation').getByRole('link', { name: 'Spletna prenova' }).click()
      await expect(form.item('web-01')).not.toBeChecked()
      await choose(page, ['web-02'], 'done')
      await page.reload()
      await expect(form.count).toHaveText('Izbrano: 0')
      await expect(form.target).toHaveValue('')
      expect(transport.calls).toHaveLength(0)
      expect(await snapshot(request)).toEqual(before)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    })

    test('A02: prazen projekt v obeh pogledih', async ({ page, request, transport }) => {
      const before = await snapshot(request)
      await page.route('**/api/projects/web/tasks', (route) => route.fulfill({ json: [] }))
      await page.goto('/')
      const form = controls(page)
      for (const view of ['Preglednica', 'Tabla']) {
        await page.getByRole('button', { name: view, exact: true }).click()
        await expect(form.all).toBeDisabled()
        await expect(form.all).not.toBeChecked()
        await expect(form.all).toHaveJSProperty('indeterminate', false)
        await expect(page.locator('[data-task-id]')).toHaveCount(0)
        await expect(form.count).toHaveText('Izbrano: 0')
        await expect(form.target).toHaveValue('')
        await form.target.selectOption('done')
        await expect(form.apply).toBeDisabled()
        await form.clear.click()
        await expect(form.target).toHaveValue('')
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      }
      expect(transport.calls).toHaveLength(0)
      expect(await snapshot(request)).toEqual(before)
    })

    test('A03: več ponovitev, kumulativni uspehi, telesa zahtev in trajni bralni prikazi', async ({ page, request, transport }) => {
      const before = await snapshot(request)
      transport.plan('web-01', ['reject', 'success'])
      transport.plan('web-02', ['reject', 'reject', 'success'])
      await page.goto('/')
      const form = await choose(page, ['web-01', 'web-02', 'web-03'], 'done')
      await form.apply.click()
      await summary(page, 1, 2)
      await onlyStatuses(request, before, ['web-03'], 'done')
      await expect(page.getByRole('alert')).toHaveCount(2)
      for (const id of ['web-01', 'web-02']) {
        const alert = page.getByRole('alert').filter({ hasText: id })
        await expect(alert).toContainText(before.tasks.find((task) => task.id === id)!.title)
        await expect(alert).toContainText('Shranjevanje ni uspelo. Poskusi znova.')
        await expect(form.item(id)).toBeChecked()
        await expect(form.item(id)).toBeDisabled()
      }
      await expect(form.item('web-03')).not.toBeChecked()
      for (const control of [form.all, form.target, form.apply, form.item('web-03')]) await expect(control).toBeDisabled()
      await expect(form.clear).toBeEnabled()
      if (viewport.width === 320) await capture(page, 'table-mobile-error')
      await page.getByRole('button', { name: 'Tabla', exact: true }).click()
      await expect(page.getByRole('region', { name: 'Tabla opravil', exact: true })).toBeVisible()
      await summary(page, 1, 2)
      await expect(form.target).toHaveValue('done')
      await expect(form.count).toHaveText('Izbrano: 2')
      await expect(page.getByRole('alert')).toHaveCount(2)
      if (viewport.width === 320) await capture(page, 'board-mobile-error')
      await form.retry.click()
      await summary(page, 2, 1)
      const middle = await onlyStatuses(request, before, ['web-01', 'web-03'], 'done')
      await presentation(page, middle.tasks, 'web', 'board')
      await expect(form.count).toHaveText('Izbrano: 1')
      await expect(form.item('web-01')).not.toBeChecked()
      await expect(form.item('web-02')).toBeChecked()
      await expect(page.getByRole('alert')).toHaveCount(1)
      await page.getByRole('button', { name: 'Preglednica', exact: true }).click()
      await summary(page, 2, 1)
      await form.retry.click()
      await summary(page, 3, 0)
      const after = await onlyStatuses(request, before, ['web-01', 'web-02', 'web-03'], 'done')
      expect(transport.calls.map(({ id }) => id).sort()).toEqual(['web-01', 'web-01', 'web-02', 'web-02', 'web-02', 'web-03'])
      for (const call of transport.calls) expect(call.body).toEqual({ title: before.tasks.find((task) => task.id === call.id)!.title, status: 'done' })
      expect(after.saveRequests - before.saveRequests).toBe(6)
      await expect(page.getByRole('alert')).toHaveCount(0)
      await expect(form.retry).toBeHidden()
      await expect(form.target).toHaveValue('')
      await expect(form.count).toHaveText('Izbrano: 0')
      await expect(form.all).not.toBeChecked()
      await expect(form.all).toHaveJSProperty('indeterminate', false)
      await presentation(page, after.tasks, 'web', 'table')
      await page.locator('[data-task-id="web-01"]').getByRole('link').click()
      await expect(page.getByRole('dialog').getByText('Končano', { exact: true })).toBeVisible()
      await expect(page.getByRole('dialog').getByText('Ana Novak', { exact: true })).toBeVisible()
      await page.keyboard.press('Escape')
      await page.getByRole('button', { name: 'Tabla', exact: true }).click()
      await summary(page, 3, 0)
      await presentation(page, after.tasks, 'web', 'board')
      await page.reload()
      await expect(form.result).toBeHidden()
      await expect(form.count).toHaveText('Izbrano: 0')
      await expect(form.target).toHaveValue('')
      await presentation(page, after.tasks, 'web', 'board')
      await page.getByRole('navigation').getByRole('link', { name: 'Jesenska kampanja' }).click()
      await presentation(page, before.tasks, 'launch', 'board')
      await page.getByRole('navigation').getByRole('link', { name: 'Spletna prenova' }).click()
      await presentation(page, after.tasks, 'web', 'board')
    })

    test('A04: popolna zavrnitev, čiščenje delnega uspeha in nova neodvisna operacija', async ({ page, request, transport }) => {
      const before = await snapshot(request)
      transport.plan('web-01', ['reject', 'success'])
      transport.plan('web-02', ['reject', 'reject'])
      await page.goto('/#/projects/web?view=board')
      const form = await choose(page, ['web-01', 'web-02'], 'done')
      await form.apply.click()
      await summary(page, 0, 2)
      expect((await snapshot(request)).tasks).toEqual(before.tasks)
      await expect(form.count).toHaveText('Izbrano: 2')
      await form.retry.click()
      await summary(page, 1, 1)
      const partial = await onlyStatuses(request, before, ['web-01'], 'done')
      await form.clear.click()
      await expect(form.result).toBeHidden()
      await expect(page.getByRole('alert')).toHaveCount(0)
      await expect(form.retry).toBeHidden()
      await expect(form.count).toHaveText('Izbrano: 0')
      await expect(form.target).toHaveValue('')
      for (const control of [form.item('web-01'), form.all, form.target]) await expect(control).toBeEnabled()
      await expect(form.apply).toBeDisabled()
      expect(await snapshot(request)).toEqual(partial)
      expect(transport.calls).toHaveLength(4)
      await choose(page, ['web-03'], 'in_progress')
      await form.apply.click()
      await summary(page, 1, 0)
      await onlyStatuses(request, partial, ['web-03'], 'in_progress')
      expect(transport.calls).toHaveLength(5)
      await form.clear.click()
      await expect(form.result).toBeHidden()
      transport.plan('web-02', ['reject', 'reject'])
      await choose(page, ['web-02'], 'todo')
      await form.apply.click()
      await summary(page, 0, 1)
      await page.reload()
      await expect(page.getByRole('alert')).toHaveCount(0)
      await expect(form.result).toBeHidden()
      await expect(form.target).toHaveValue('')
      await expect(form.count).toHaveText('Izbrano: 0')
      await choose(page, ['web-02'], 'todo')
      await form.apply.click()
      await summary(page, 0, 1)
      await page.getByRole('navigation').getByRole('link', { name: 'Jesenska kampanja' }).click()
      await expect(form.count).toHaveText('Izbrano: 0')
      await expect(form.target).toHaveValue('')
      await expect(form.result).toBeHidden()
      await expect(page.getByRole('alert')).toHaveCount(0)
      await page.getByRole('navigation').getByRole('link', { name: 'Spletna prenova' }).click()
      await expect(form.item('web-02')).not.toBeChecked()
      await expect(form.target).toHaveValue('')
      await expect(form.result).toBeHidden()
      await expect(page.getByRole('alert')).toHaveCount(0)
      await onlyStatuses(request, partial, ['web-03'], 'in_progress')
    })

    test('A05: sprotni uspeh ob čakajoči zavrnitvi, zaklep in hitri pritiski', async ({ page, request, transport }) => {
      const before = await snapshot(request)
      transport.plan('web-01', ['hold-reject', 'success'])
      await page.goto('/')
      const form = await choose(page, ['web-01', 'web-02'], 'in_progress')
      await form.apply.focus()
      // Dispatch several clicks within one browser turn, also exercising the synchronous guard.
      await form.apply.evaluate((button) => {
        for (let i = 0; i < 4; i++) button.dispatchEvent(new MouseEvent('click', { bubbles: true }))
      })
      await page.keyboard.press('Enter')
      await page.keyboard.press('Enter')
      await expect(form.progress).toContainText('1 / 2')
      await expect(form.result).toBeHidden()
      for (const control of [form.all, form.target, form.apply, form.retry, form.clear, form.item('web-01'), form.item('web-02'), form.item('web-03')]) await expect(control).toBeDisabled()
      const partial = await onlyStatuses(request, before, ['web-02'], 'in_progress')
      await presentation(page, partial.tasks, 'web', 'table')
      await page.getByRole('button', { name: 'Tabla', exact: true }).click()
      await expect(form.progress).toContainText('1 / 2')
      await presentation(page, partial.tasks, 'web', 'board')
      expect(transport.calls.map(({ id }) => id).sort()).toEqual(['web-01', 'web-02'])
      transport.releaseAll()
      await summary(page, 1, 1)
      await onlyStatuses(request, before, ['web-02'], 'in_progress')
      await expect(form.item('web-01')).toBeChecked()
      await expect(form.item('web-02')).not.toBeChecked()
      await form.retry.evaluate((button) => {
        for (let i = 0; i < 4; i++) button.dispatchEvent(new MouseEvent('click', { bubbles: true }))
      })
      await summary(page, 2, 0)
      await onlyStatuses(request, before, ['web-01', 'web-02'], 'in_progress')
      expect(transport.calls.map(({ id }) => id).sort()).toEqual(['web-01', 'web-01', 'web-02'])
      await page.locator('[data-task-id="web-02"]').getByRole('link').click()
      await expect(page.getByRole('dialog').getByText(labels.in_progress, { exact: true })).toBeVisible()
      await page.keyboard.press('Escape')
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    })

    test('A06: drugi projekt, spremenjeni naslovi in pozni uspeh po zavrnitvi', async ({ page, request, transport }) => {
      const title = 'Pregled vsebine — ŠČŽ & načrt / 2026'
      for (const id of ['launch-01', 'launch-02']) {
        expect((await request.patch(`/api/tasks/${id}`, { data: { title, status: 'done' } })).status()).toBe(200)
      }
      const before = await snapshot(request)
      transport.plan('launch-01', ['reject', 'success'])
      transport.plan('launch-02', ['hold-success'])
      await page.goto('/#/projects/launch?view=board')
      const form = controls(page)
      await form.all.check()
      await expect(form.count).toHaveText('Izbrano: 3')
      await form.target.selectOption('todo')
      await form.apply.click()
      await expect(form.progress).toContainText('2 / 3')
      const partial = await onlyStatuses(request, before, ['launch-03'], 'todo')
      await presentation(page, partial.tasks, 'launch', 'board')
      await expect(form.clear).toBeDisabled()
      await expect(form.all).toBeDisabled()
      await expect(form.target).toHaveValue('todo')
      transport.releaseAll()
      await summary(page, 2, 1)
      const after = await onlyStatuses(request, before, ['launch-02', 'launch-03'], 'todo')
      await presentation(page, after.tasks, 'launch', 'board')
      await expect(page.getByRole('alert')).toContainText(title)
      await expect(form.all).toHaveJSProperty('indeterminate', true)
      await expect(form.count).toHaveText('Izbrano: 1')
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await form.retry.click()
      await summary(page, 3, 0)
      await onlyStatuses(request, before, ['launch-01', 'launch-02', 'launch-03'], 'todo')
      expect(transport.calls.map(({ id }) => id).sort()).toEqual(['launch-01', 'launch-01', 'launch-02', 'launch-03'])
      for (const call of transport.calls) expect(call.body).toEqual({ title: before.tasks.find((task) => task.id === call.id)!.title, status: 'todo' })
    })
  })
}
