test("A14: brez zapisov na API in brez sprememb polj opravil", async ({ page }) => {
  const writes = await mount(page)
  await favoriteButton(page, "web-02").click()
  await filterBox(page).check()
  await board(page)
  await click(page, "Odstrani priljubljene tega projekta")
  await filterBox(page).uncheck()
  expect(writes).toEqual([])
  const tasks = await page.evaluate(() => fetch("/api/projects/web/tasks").then((response) => response.json()))
  expect(tasks).toHaveLength(8)
  expect(tasks[1]).toMatchObject({ id: "web-02", title: "Pregled vsebine", status: "todo", assignee: "Luka Kovač" })
})

