test('R05: assignee options cover the whole project, once, and reset on project change', async ({ page }) => {
  await mount(page)
  const assignee = page.getByRole('combobox', { name: 'Filter odgovorne osebe' })
  const options = ['Vse osebe', 'Ana Novak', 'Luka Kovač', 'Maja Zupan', 'Živa Kovač', 'Črt']
  await expect(assignee.locator('option')).toHaveText(options)
  await select(page, 'Filter stanja', 'done')
  await page.getByRole('searchbox', { name: 'Išči opravila' }).fill('neobstojece')
  await expect(assignee.locator('option')).toHaveText(options)
  await project(page, 'launch')
  await expect(assignee).toHaveValue('all')
  await expect(assignee.locator('option')).toHaveText(['Vse osebe', 'Ana Novak', 'Luka Kovač'])
  await expectIds(page, ['launch-01', 'launch-02'])
})

