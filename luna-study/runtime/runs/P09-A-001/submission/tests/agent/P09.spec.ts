import { expect, test, mount, expectIds, webIds, click } from '../development/helpers.ts'

test('P09: literal Unicode search combines fields and status with AND', async ({ page }) => {
  await mount(page, undefined, '#/projects/web?q=CSZ')
  await expectIds(page, ['web-06'])
  await expect(page.getByRole('status', { name: 'Rezultati povezave' })).toHaveText('Prikazano: 1 od 8.')

  await page.getByRole('searchbox', { name: 'Iskanje v povezavi' }).fill('^=SUM')
  await click(page, 'Uporabi pogled')
  await expectIds(page, [])
  await expect(page.getByText('Ni zadetkov.')).toBeVisible()

  await page.getByRole('searchbox', { name: 'Iskanje v povezavi' }).fill('Pregled vsebine')
  await page.getByRole('combobox', { name: 'Stanje v povezavi' }).selectOption('done')
  await click(page, 'Uporabi pogled')
  await expectIds(page, ['web-03'])

  await page.getByRole('searchbox', { name: 'Iskanje v povezavi' }).fill('web-04')
  await page.getByRole('combobox', { name: 'Stanje v povezavi' }).selectOption('all')
  await click(page, 'Uporabi pogled')
  await expectIds(page, ['web-04'])
  await page.getByRole('searchbox', { name: 'Iskanje v povezavi' }).fill('ziva')
  await click(page, 'Uporabi pogled')
  await expectIds(page, ['web-06'])
})

test('P09: duplicate and unknown parameters use defaults without rewriting until confirmation', async ({ page }) => {
  const direct = '#/projects/web?view=board&q=%20Pregled%20&status=todo&status=done&order=invalid&extra=x'
  await mount(page, undefined, direct)
  await expectIds(page, ['web-02'])
  await expect(page.getByRole('searchbox', { name: 'Iskanje v povezavi' })).toHaveValue(' Pregled ')
  await expect(page.getByRole('combobox', { name: 'Stanje v povezavi' })).toHaveValue('todo')
  expect(new URL(page.url()).hash).toBe(direct)

  const length = await page.evaluate(() => history.length)
  await click(page, 'Uporabi pogled')
  await expect.poll(() => new URL(page.url()).hash).toContain('q=Pregled')
  expect(new URL(page.url()).hash).not.toContain('extra')
  expect(new URL(page.url()).hash).toContain('view=board')
  expect(await page.evaluate(() => history.length)).toBe(length)
})

test('P09: draft is not applied, view navigation discards it, and confirmation is idempotent', async ({ page }) => {
  await mount(page)
  const search = page.getByRole('searchbox', { name: 'Iskanje v povezavi' })
  await search.fill('Pregled')
  await expectIds(page, webIds())
  await click(page, 'Tabla')
  await expectIds(page, webIds(), false)
  await expect(search).toHaveValue('')

  await search.fill('Pregled')
  const before = await page.evaluate(() => history.length)
  await click(page, 'Uporabi pogled')
  await expectIds(page, ['web-01', 'web-02', 'web-03'], false)
  expect(await page.evaluate(() => history.length)).toBe(before + 1)
  const afterApply = await page.evaluate(() => history.length)
  await click(page, 'Uporabi pogled')
  expect(await page.evaluate(() => history.length)).toBe(afterApply)
})

test('P09: browser back and forward restore filters, results, and draft', async ({ page }) => {
  await mount(page)
  await page.getByRole('searchbox', { name: 'Iskanje v povezavi' }).fill('Pregled')
  await click(page, 'Uporabi pogled')
  await expectIds(page, ['web-01', 'web-02', 'web-03'])
  await page.getByRole('combobox', { name: 'Stanje v povezavi' }).selectOption('done')
  await click(page, 'Uporabi pogled')
  await expectIds(page, ['web-03'])

  await page.goBack()
  await expectIds(page, ['web-01', 'web-02', 'web-03'])
  await expect(page.getByRole('combobox', { name: 'Stanje v povezavi' })).toHaveValue('all')
  await page.goForward()
  await expectIds(page, ['web-03'])
})

test('P09: project links reset filters, while details preserve filters and board mode', async ({ page }) => {
  await mount(page, undefined, '#/projects/web?view=board&q=pregled&status=done&order=title-desc')
  await expectIds(page, ['web-03'])
  await page.locator('[data-task-id="web-03"]').getByRole('link').click()
  await expect(page.getByRole('dialog')).toBeVisible()
  expect(new URL(page.url()).hash).toContain('view=board')
  expect(new URL(page.url()).hash).toContain('status=done')
  await page.getByRole('button', { name: 'Zapri podrobnosti' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(new URL(page.url()).hash).toContain('status=done')

  await page.locator('[data-task-id="web-03"]').getByRole('link').click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(new URL(page.url()).hash).toContain('q=pregled')
  expect(new URL(page.url()).hash).toContain('order=title-desc')

  await page.getByRole('navigation', { name: 'Projekti' }).getByRole('link', { name: 'Jesenska kampanja' }).click()
  await expect(page.getByRole('heading', { name: 'Jesenska kampanja' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Tabla', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect(new URL(page.url()).hash).not.toContain('q=')
  expect(new URL(page.url()).hash).not.toContain('status=')
  await expectIds(page, ['launch-01', 'launch-02'])

  await page.goto('/#/projects/launch?status=done')
  await expectIds(page, ['launch-02'])

  await page.goto('/#/projects/web/tasks/web-03?view=board&q=pregled&status=done')
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('dialog').getByText('web-03', { exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Zapri podrobnosti' }).click()
  await expectIds(page, ['web-03'])
  await expect(page.getByRole('combobox', { name: 'Stanje v povezavi' })).toHaveValue('done')
})

test('P09: title sorting is normalized, stable for equal titles, and stays within the page on mobile width', async ({ page }) => {
  await mount(page, undefined, '#/projects/web?order=title-asc')
  await expectIds(page, ['web-07', 'web-04', 'web-05', 'web-01', 'web-08', 'web-02', 'web-03', 'web-06'])
  const sameTitleOrder = await page.locator('tr[data-task-id]').evaluateAll(rows => rows.map(row => row.getAttribute('data-task-id')).filter(id => id === 'web-02' || id === 'web-03'))
  expect(sameTitleOrder).toEqual(['web-02', 'web-03'])
  await page.getByRole('combobox', { name: 'Vrstni red' }).selectOption('title-desc')
  await click(page, 'Uporabi pogled')
  await expectIds(page, ['web-06', 'web-02', 'web-03', 'web-08', 'web-01', 'web-05', 'web-04', 'web-07'])
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

