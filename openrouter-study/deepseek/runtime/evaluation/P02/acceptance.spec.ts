test('E06: zadržane zahteve zaklenejo vnos, hitri pritiski ne podvajajo [R04,R05,R10]', async ({ page, request, transport }) => {
  const before = await snapshot(request)
  for (const id of ['web-01', 'web-02']) transport.plan(id, ['hold-success'])
  await page.goto('/')
  const form = await choose(page, ['web-01', 'web-02'], 'done')
  await form.apply.evaluate((button: HTMLButtonElement) => { button.click(); button.click() })
  await expect(form.progress).toBeVisible()
  for (const control of [form.all, form.item('web-01'), form.item('web-02'), form.item('web-03'), form.target, form.apply, form.clear]) await expect(control).toBeDisabled()
  await page.keyboard.press('Enter')
  await page.keyboard.press('Enter')
  expect((await snapshot(request)).tasks).toEqual(before.tasks)
  await presentation(page, before.tasks, 'web', 'table')
  transport.releaseAll()
  await summary(page, 2, 0)
  expect(transport.calls.map((call) => call.id).sort()).toEqual(['web-01', 'web-02'])
  await onlyStatuses(request, before, ['web-01', 'web-02'], 'done')
})

test('E07: več delnih neuspehov, pravilna sporočila in ponavljanje samo preostalih [R07,R08,R09,R10]', async ({ page, request, transport }) => {
  const before = await snapshot(request)
  transport.plan('web-01', ['reject', 'success'])
  transport.plan('web-03', ['reject', 'reject', 'success'])
  await page.goto('/')
  const form = await choose(page, ['web-01', 'web-02', 'web-03'], 'in_progress')
  await form.apply.click()
  await summary(page, 1, 2)
  await onlyStatuses(request, before, ['web-02'], 'in_progress')
  for (const id of ['web-01', 'web-03']) {
    await expect(form.item(id)).toBeChecked()
    await expect(page.getByRole('alert').filter({ hasText: id })).toContainText(before.tasks.find((task) => task.id === id)!.title)
  }
  await expect(page.getByRole('alert')).toHaveCount(2)
  await expect(form.item('web-02')).not.toBeChecked()
  for (const control of [form.all, form.item('web-01'), form.target, form.apply]) await expect(control).toBeDisabled()
  await expect(form.target).toHaveValue('in_progress')
  await expect(form.clear).toBeEnabled()
  await form.retry.click()
  await summary(page, 2, 1)
  await onlyStatuses(request, before, ['web-01', 'web-02'], 'in_progress')
  await expect(form.count).toHaveText('Izbrano: 1')
  await expect(form.item('web-03')).toBeChecked()
  await expect(page.getByRole('alert')).toHaveCount(1)
  await expect(page.getByRole('alert')).toContainText('web-03')
  await form.retry.click()
  await summary(page, 3, 0)
  await onlyStatuses(request, before, ['web-01', 'web-02', 'web-03'], 'in_progress')
  expect(transport.calls.map((call) => call.id).sort()).toEqual(['web-01', 'web-01', 'web-02', 'web-03', 'web-03', 'web-03'])
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(form.count).toHaveText('Izbrano: 0')
  await expect(form.target).toHaveValue('')
  expect(await form.retry.isVisible() && await form.retry.isEnabled()).toBe(false)
})

test('E08: potrjeni uspeh je viden pred poznejšo zavrnitvijo [R06,R07,R10]', async ({ page, request, transport }) => {
  const before = await snapshot(request)
  transport.inOrder(['success', 'hold-reject'])
  await page.goto('/')
  const form = await choose(page, ['web-01', 'web-02'], 'done')
  await form.apply.click()
  await expect.poll(() => transport.calls.length).toBe(2)
  const successId = transport.calls[0].id
  await expect(page.locator(`[data-task-id="${successId}"]`)).toContainText('Končano')
  await expect(form.progress).toBeVisible()
  const intermediate = await onlyStatuses(request, before, [successId], 'done')
  await presentation(page, intermediate.tasks, 'web', 'table')
  transport.releaseAll()
  await summary(page, 1, 1)
  await onlyStatuses(request, before, [successId], 'done')
  await expect(form.item(transport.calls[1].id)).toBeChecked()
})

