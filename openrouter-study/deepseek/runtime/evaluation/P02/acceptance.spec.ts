test('E13: osvežitev, podrobnosti in števci po delnem uspehu [R03,R06,R12]', async ({ page, request, transport }) => {
  const before = await snapshot(request)
  transport.plan('launch-01', ['reject'])
  await page.goto('/#/projects/launch?view=board')
  const form = await choose(page, ['launch-01', 'launch-02'], 'done')
  await form.apply.click()
  await summary(page, 1, 1)
  const after = await onlyStatuses(request, before, ['launch-02'], 'done')
  await page.reload()
  await expect(form.count).toHaveText('Izbrano: 0')
  await expect(form.target).toHaveValue('')
  await expect(form.result).toBeHidden()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await presentation(page, after.tasks, 'launch', 'board')
  for (const id of ['launch-01', 'launch-02']) {
    await page.locator(`[data-task-id="${id}"]`).getByRole('link').click()
    const task = after.tasks.find((entry) => entry.id === id)!
    await expect(page.getByRole('dialog').getByRole('heading', { name: task.title, exact: true })).toBeVisible()
    await expect(page.getByRole('dialog').getByText(labels[task.status], { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Zapri podrobnosti' }).click()
  }
  await page.getByRole('button', { name: 'Preglednica', exact: true }).click()
  await presentation(page, after.tasks, 'launch', 'table')
  expect(await snapshot(request)).toEqual(after)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
})
