import { choose, controls, expect, labels, onlyStatuses, presentation, reset, snapshot, summary, test } from '../development/helpers.ts'

test.beforeEach(async ({ request }) => { await reset(request) })

for (const width of [1440, 390]) {
  test(`E01: selection, duplicate titles, select all and view preservation at ${width}px`, async ({ page, request, transport }) => {
    await page.setViewportSize({ width, height: 960 })
    const before = await snapshot(request)
    await page.goto('/')
    const form = controls(page)
    await expect(form.count).toHaveText('Izbrano: 0')
    await expect(form.target).toHaveValue('')
    await expect(form.apply).toBeDisabled()
    await form.target.selectOption('done')
    await expect(form.apply).toBeDisabled()
    await form.item('web-01').check()
    await expect(form.item('web-02')).not.toBeChecked()
    await expect(form.all).toHaveJSProperty('indeterminate', true)
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await page.getByRole('button', { name: 'Tabla', exact: true }).click()
    await expect(form.item('web-01')).toBeChecked()
    await expect(form.target).toHaveValue('done')
    await form.item('web-02').check()
    await expect(form.count).toHaveText('Izbrano: 2')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await form.all.check()
    await expect(form.count).toHaveText('Izbrano: 3')
    await expect(form.all).toHaveJSProperty('indeterminate', false)
    await form.all.uncheck()
    await expect(form.count).toHaveText('Izbrano: 0')
    await form.item('web-02').check()
    await form.target.selectOption('')
    await expect(form.apply).toBeDisabled()
    await form.clear.click()
    await expect(form.count).toHaveText('Izbrano: 0')
    await expect(form.target).toHaveValue('')
    expect(await snapshot(request)).toEqual(before)
    expect(transport.calls).toEqual([])
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })

  test(`E05: cumulative retries, exact bodies and locked failures at ${width}px`, async ({ page, request, transport }, testInfo) => {
    await page.setViewportSize({ width, height: 960 })
    const before = await snapshot(request)
    transport.plan('web-01', ['reject', 'success'])
    transport.plan('web-02', ['reject', 'reject', 'success'])
    await page.goto('/')
    const form = await choose(page, ['web-01', 'web-02', 'web-03'], 'done')
    await form.apply.click()
    await summary(page, 1, 2)
    await onlyStatuses(request, before, ['web-03'], 'done')
    await expect(page.getByRole('alert')).toHaveCount(2)
    for (const id of ['web-01', 'web-02']) {
      await expect(page.getByRole('alert').filter({ hasText: id })).toContainText(before.tasks.find((task) => task.id === id)!.title)
      await expect(form.item(id)).toBeChecked()
    }
    await expect(form.item('web-03')).not.toBeChecked()
    for (const control of [form.all, form.item('web-01'), form.item('web-03'), form.target, form.apply]) await expect(control).toBeDisabled()
    await expect(form.clear).toBeEnabled()
    await page.getByRole('button', { name: 'Tabla', exact: true }).click()
    await summary(page, 1, 2)
    await expect(form.target).toHaveValue('done')
    await expect(form.item('web-02')).toBeDisabled()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`bulk-failure-${width}.png`), fullPage: true })
    await form.retry.click()
    await summary(page, 2, 1)
    await expect(form.count).toHaveText('Izbrano: 1')
    await onlyStatuses(request, before, ['web-01', 'web-03'], 'done')
    await expect(page.getByRole('alert')).toHaveCount(1)
    await form.retry.click()
    await summary(page, 3, 0)
    await expect(form.count).toHaveText('Izbrano: 0')
    await expect(form.target).toHaveValue('')
    await expect(page.getByRole('alert')).toHaveCount(0)
    await expect(form.retry).toBeHidden()
    await expect(form.item('web-01')).toBeEnabled()
    expect(transport.calls.map(({ id }) => id).sort()).toEqual(['web-01', 'web-01', 'web-02', 'web-02', 'web-02', 'web-03'])
    for (const call of transport.calls) expect(call.body).toEqual({ title: before.tasks.find((task) => task.id === call.id)!.title, status: 'done' })
    const after = await onlyStatuses(request, before, ['web-01', 'web-02', 'web-03'], 'done')
    await presentation(page, after.tasks, 'web', 'board')
    await page.getByRole('button', { name: 'Preglednica', exact: true }).click()
    await summary(page, 3, 0)
    await presentation(page, after.tasks, 'web', 'table')
    await page.screenshot({ path: testInfo.outputPath(`bulk-success-${width}.png`), fullPage: true })
  })
}

test('E01-empty: empty project disables the unchecked master checkbox in both views', async ({ page, request, transport }) => {
  const before = await snapshot(request)
  await page.route('**/api/projects/web/tasks', (route) => route.fulfill({ json: [] }))
  await page.goto('/')
  const form = controls(page)
  for (const view of ['Preglednica', 'Tabla']) {
    await page.getByRole('button', { name: view, exact: true }).click()
    await expect(form.all).toBeDisabled()
    await expect(form.all).not.toBeChecked()
    await expect(form.all).toHaveJSProperty('indeterminate', false)
    await expect(form.count).toHaveText('Izbrano: 0')
    await expect(form.apply).toBeDisabled()
  }
  expect(transport.calls).toEqual([])
  expect(await snapshot(request)).toEqual(before)
})

for (const target of ['todo', 'in_progress', 'done'] as const) {
  test(`E03: exact PATCH snapshots, immutable fields and persisted ${target}`, async ({ page, request, transport }) => {
    const before = await snapshot(request)
    await page.goto('/')
    const form = await choose(page, ['web-01', 'web-02', 'web-03'], target)
    await presentation(page, before.tasks, 'web', 'table')
    expect(transport.calls).toHaveLength(0)
    await form.apply.click()
    await summary(page, 3, 0)
    expect(transport.calls.map(({ id }) => id).sort()).toEqual(['web-01', 'web-02', 'web-03'])
    for (const call of transport.calls) expect(call.body).toEqual({ title: before.tasks.find((task) => task.id === call.id)!.title, status: target })
    const after = await onlyStatuses(request, before, ['web-01', 'web-02', 'web-03'], target)
    await presentation(page, after.tasks, 'web', 'table')
    await page.locator('[data-task-id="web-02"]').getByRole('link').click()
    await expect(page.getByRole('dialog').getByText(labels[target], { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Zapri podrobnosti' }).click()
    await page.getByRole('button', { name: 'Tabla', exact: true }).click()
    await presentation(page, after.tasks, 'web', 'board')
    await page.reload()
    await presentation(page, after.tasks, 'web', 'board')
    await expect(form.result).toBeHidden()
    await expect(form.count).toHaveText('Izbrano: 0')
    await expect(form.target).toHaveValue('')
  })
}

test('E04: individual success is visible while another response waits; rapid events cannot duplicate writes', async ({ page, request, transport }) => {
  const before = await snapshot(request)
  transport.plan('web-02', ['hold-reject'])
  await page.goto('/')
  const form = await choose(page, ['web-01', 'web-02'], 'done')
  await form.apply.evaluate((button) => { (button as HTMLButtonElement).click(); (button as HTMLButtonElement).click() })
  await page.keyboard.press('Enter')
  await expect(form.progress).toBeVisible()
  await expect(page.locator('[data-task-id="web-01"]')).toContainText('Končano')
  await expect(page.locator('[data-task-id="web-02"]')).toContainText('Pripravljeno')
  const partial = await onlyStatuses(request, before, ['web-01'], 'done')
  await presentation(page, partial.tasks, 'web', 'table')
  await page.getByRole('button', { name: 'Tabla', exact: true }).click()
  await presentation(page, partial.tasks, 'web', 'board')
  for (const control of [form.all, form.item('web-01'), form.item('web-02'), form.item('web-03'), form.target, form.apply, form.clear]) await expect(control).toBeDisabled()
  expect(transport.calls.map(({ id }) => id).sort()).toEqual(['web-01', 'web-02'])
  transport.releaseAll()
  await summary(page, 1, 1)
  await onlyStatuses(request, before, ['web-01'], 'done')
  await form.clear.click()
  await expect(form.result).toBeHidden()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(form.target).toHaveValue('')
  await expect(form.count).toHaveText('Izbrano: 0')
  expect(transport.calls).toHaveLength(2)
  await choose(page, ['web-03'], 'todo')
  await form.apply.click()
  await summary(page, 1, 0)
  await onlyStatuses(request, partial, ['web-03'], 'todo')
})

test('E02/E06: total rejection, repeated rejection, project reset and refresh reset', async ({ page, request, transport }) => {
  const before = await snapshot(request)
  transport.plan('web-01', ['reject', 'reject'])
  transport.plan('web-02', ['reject', 'reject'])
  await page.goto('/')
  const form = await choose(page, ['web-01', 'web-02'], 'done')
  await form.apply.click()
  await summary(page, 0, 2)
  await form.retry.click()
  await summary(page, 0, 2)
  await expect(form.count).toHaveText('Izbrano: 2')
  expect((await snapshot(request)).tasks).toEqual(before.tasks)
  await page.getByRole('navigation').getByRole('link', { name: 'Jesenska kampanja' }).click()
  await expect(form.count).toHaveText('Izbrano: 0')
  await expect(form.target).toHaveValue('')
  await expect(form.result).toBeHidden()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByRole('navigation').getByRole('link', { name: 'Spletna prenova' }).click()
  await expect(form.count).toHaveText('Izbrano: 0')
  await expect(form.target).toHaveValue('')
  await expect(form.item('web-01')).toBeEnabled()
  await choose(page, ['web-02'], 'in_progress')
  await page.reload()
  await expect(form.count).toHaveText('Izbrano: 0')
  await expect(form.target).toHaveValue('')
  await expect(form.result).toBeHidden()
  expect(transport.calls).toHaveLength(4)
  expect((await snapshot(request)).tasks).toEqual(before.tasks)
})

test('E10: a pending retry disables every action and sends each failed ID once', async ({ page, request, transport }) => {
  const before = await snapshot(request)
  transport.plan('web-02', ['reject', 'hold-success'])
  await page.goto('/')
  const form = await choose(page, ['web-01', 'web-02'], 'done')
  await form.apply.click()
  await summary(page, 1, 1)
  await form.retry.evaluate((button) => { (button as HTMLButtonElement).click(); (button as HTMLButtonElement).click() })
  await page.keyboard.press('Enter')
  await expect(form.progress).toBeVisible()
  for (const control of [form.all, form.item('web-01'), form.item('web-02'), form.item('web-03'), form.target, form.apply, form.retry, form.clear]) await expect(control).toBeDisabled()
  await page.getByRole('button', { name: 'Tabla', exact: true }).click()
  await expect(form.retry).toBeDisabled()
  await expect(form.item('web-02')).toBeDisabled()
  await onlyStatuses(request, before, ['web-01'], 'done')
  expect(transport.calls.map(({ id }) => id).sort()).toEqual(['web-01', 'web-02', 'web-02'])
  transport.releaseAll()
  await summary(page, 2, 0)
  await expect(form.retry).toBeHidden()
  await onlyStatuses(request, before, ['web-01', 'web-02'], 'done')
})
