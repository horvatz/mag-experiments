test('R02 and R04: size 10 handles more than ten records and all returns one page', async ({ page }) => {
  const records = Array.from({ length: 11 }, (_, index) => makeTask(`web-${index + 1}`))
  await mount(page, records)
  await select(page, 'Velikost strani', '10')
  await expectIds(page, records.slice(0, 10).map((task) => task.id))
  await click(page, 'Naslednja stran')
  await expectIds(page, ['web-11'])
  await expect(page.getByRole('status', { name: 'Stanje straničenja' })).toHaveText('Stran 2 od 2. Prikazano 11–11 od 11.')
  await expect(page.getByRole('button', { name: 'Zadnja stran' })).toBeDisabled()
  await select(page, 'Velikost strani', 'all')
  await expectIds(page, records.map((task) => task.id))
  await expect(page.getByRole('status', { name: 'Stanje straničenja' })).toHaveText('Stran 1 od 1. Prikazano 1–11 od 11.')
})
