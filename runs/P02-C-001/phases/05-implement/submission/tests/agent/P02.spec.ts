import { choose, controls, expect, labels, onlyStatuses, reset, snapshot, summary, test } from '../development/helpers.ts'

test.beforeEach(async ({ request }) => { await reset(request) })

for (const width of [1440, 390]) {
  test(`A01-${width}: izbor po ID, skupno polje in Folio v obeh pogledih`, async ({ page, request, transport }) => {
    await page.setViewportSize({ width, height: 960 })
    const before = await snapshot(request)
    await page.goto('/')
    const f = controls(page)
    await expect(f.count).toHaveText('Izbrano: 0')
    await expect(f.target).toHaveValue('')
    await expect(f.apply).toBeDisabled()
    await f.target.selectOption('in_progress')
    await expect(f.apply).toBeDisabled()
    await f.item('web-02').check()
    await expect(f.item('web-01')).not.toBeChecked()
    await expect(f.all).toHaveJSProperty('indeterminate', true)
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(f.apply).toBeEnabled()
    await page.getByRole('button', { name: 'Tabla', exact: true }).click()
    await expect(f.item('web-02')).toBeChecked()
    await expect(f.target).toHaveValue('in_progress')
    await f.item('web-01').check()
    await expect(f.count).toHaveText('Izbrano: 2')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await f.all.check()
    await expect(f.count).toHaveText('Izbrano: 3')
    await expect(f.all).toHaveJSProperty('indeterminate', false)
    await f.all.uncheck()
    await expect(f.count).toHaveText('Izbrano: 0')
    await f.item('web-02').focus()
    await page.keyboard.press('Space')
    await expect(f.item('web-02')).toBeChecked()
    await expect(f.item('web-02')).toBeFocused()
    await expect(f.item('web-02')).toHaveCSS('outline-style', 'solid')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBeTruthy()
    await page.screenshot({ path: `docs/agent/P02/folio-${width}.png`, fullPage: true })
    await page.getByRole('button', { name: 'Preglednica', exact: true }).click()
    await expect(f.item('web-02')).toBeChecked()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBeTruthy()
    await f.clear.click()
    await expect(f.target).toHaveValue('')
    expect(transport.calls).toEqual([])
    expect(await snapshot(request)).toEqual(before)
  })
}

