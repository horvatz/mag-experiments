test('R11: reset clears filters and draft, keeps view and follows the history rule', async ({ page }) => {
  await mount(page, '#/projects/web?view=board&q=neobstojece&status=todo')
  await expect(page.getByText('Ni zadetkov.')).toBeVisible()
  await expect(counter(page)).toHaveText('Prikazano: 0 od 6.')
  const before = await historyLength(page)
  await press(page, 'Ponastavi pogled')
  await expect(page.getByRole('region', { name: 'Tabla opravil', exact: true })).toBeVisible()
  await expectIdsUnordered(page, allWebIds)
  await expect(page.getByRole('searchbox', { name: 'Iskanje v povezavi', exact: true })).toHaveValue('')
  await expect(page.getByRole('combobox', { name: 'Stanje v povezavi', exact: true })).toHaveValue('all')
  await expect(counter(page)).toHaveText('Prikazano: 6 od 6.')
  expect(hashParams(page).get('view')).toBe('board')
  expect(hashParams(page).get('q')).toBeNull()
  expect(await historyLength(page)).toBe(before + 1)
  await press(page, 'Ponastavi pogled')
  expect(await historyLength(page)).toBe(before + 1)
  await mount(page, '#/projects/web?status=done')
  await expect(counter(page)).toHaveText('Prikazano: 2 od 6.')
})

test('R12: only read requests, no localStorage, baseline states and narrow layout keep working', async ({ page }) => {
  const writes = await mount(page, '#/projects/web?q=pregled')
  await press(page, 'Uporabi pogled')
  await page.locator('[data-task-id="web-1"]').getByRole('link').click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  expect(writes).toEqual([])
  expect(await page.evaluate(() => localStorage.length)).toBe(0)
  await page.goto('/#/projects/missing')
  await expect(page.getByRole('heading', { name: 'Projekt ne obstaja' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#/projects/web?q=pregled&status=all')
  await expect(page.getByRole('heading', { name: 'Spletna prenova', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBeTruthy()
})
