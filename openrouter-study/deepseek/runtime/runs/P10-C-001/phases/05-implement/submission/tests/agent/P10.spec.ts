test('A07: undo history keeps at most 20 entries, redo replays them', async ({ page }) => {
  await mount(page)
  for (let step = 0; step < 21; step += 1) await click(page, step % 2 === 0 ? 'Premakni web-02 gor' : 'Premakni web-02 dol')
  await expect(history(page)).toHaveText('Razveljavitve: 20. Ponovitve: 0.')
  const finalIds = ['web-02', 'web-01', 'web-03', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08']
  await expectIds(page, finalIds)
  for (let step = 0; step < 20; step += 1) await click(page, 'Razveljavi premik')
  await expect(history(page)).toHaveText('Razveljavitve: 0. Ponovitve: 20.')
  await expect(page.getByRole('button', { name: 'Razveljavi premik', exact: true })).toBeDisabled()
  await expectIds(page, finalIds)
  for (let step = 0; step < 20; step += 1) await click(page, 'Ponovi premik')
  await expect(history(page)).toHaveText('Razveljavitve: 20. Ponovitve: 0.')
  await expectIds(page, finalIds)
})

test('A08: board keeps columns and uses global neighbour without status change', async ({ page }) => {
  await mount(page)
  await board(page)
  await expect.poll(() => columnIds(page, '.board-todo')).toEqual(['web-02', 'web-04', 'web-07', 'web-08'])
  await expect.poll(() => columnIds(page, '.board-in_progress')).toEqual(['web-01', 'web-05'])
  await expect.poll(() => columnIds(page, '.board-done')).toEqual(['web-03', 'web-06'])
  await click(page, 'Premakni web-02 gor')
  await expect(rank(page, 'web-02')).toHaveText('1')
  await expect(page.locator('.board-todo [data-task-id]').first()).toHaveAttribute('data-task-id', 'web-02')
  await expect(page.locator('.board-in_progress [data-task-id]').first()).toHaveAttribute('data-task-id', 'web-01')
  await expect.poll(() => columnIds(page, '.board-done')).toEqual(['web-03', 'web-06'])
})

