import { useCallback, useEffect, useState } from 'react'
import { request } from './api.ts'

export function useResource<T>(path: string | null) {
  const [attempt, setAttempt] = useState(0)
  const key = `${path}:${attempt}`
  const [result, setResult] = useState<{ key: string; data: T | null; error: string | null } | null>(null)
  const retry = useCallback(() => setAttempt((value) => value + 1), [])
  const updateData = useCallback((update: (data: T) => T) => {
    setResult((current) => current?.data !== null && current?.data !== undefined
      ? { ...current, data: update(current.data) }
      : current)
  }, [])

  useEffect(() => {
    if (!path) return
    const controller = new AbortController()
    request<T>(path, { signal: controller.signal })
      .then((data) => {
        if (!controller.signal.aborted) setResult({ key, data, error: null })
      })
      .catch((error: unknown) => {
        if (!controller.signal.aborted) {
          setResult({ key, data: null, error: error instanceof Error ? error.message : 'Podatkov ni mogoče pridobiti.' })
        }
      })
    return () => controller.abort()
  }, [path, key])

  const current = result?.key === key ? result : null
  return { data: current?.data ?? null, error: current?.error ?? null, loading: !!path && !current, retry, updateData }
}
