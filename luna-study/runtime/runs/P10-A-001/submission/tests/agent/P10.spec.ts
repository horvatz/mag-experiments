test('P10: lists longer than ten tasks preserve distinct IDs and duplicate titles', async ({ page }) => {
  const records = Array.from({ length: 12 }, (_, index) => makeTask(`item-${index + 1}`, { title: 'Enak naslov' }))
  const ids = records.map((task) => task.id)
  const writes = await mount(page, records)
  await expectIds(page, ids)
  await expect(page.getByLabel('Mesto opravila item-12', { exact: true })).toHaveText('12')
  await click(page, 'Premakni item-12 gor')
  await expectIds(page, [...ids.slice(0, 10), 'item-12', 'item-11'])
  expect(await page.getByRole('row', { name: /Enak naslov/ }).count()).toBe(12)
  expect(writes).toEqual([])
})

