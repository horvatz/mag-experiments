test("P07-R11: dogodki storage, tuj ključ in brez povratnega zapisa", async ({ page }) => {
  const raw = JSON.stringify({ version: 1, ids: ["web-02", "web-02", "nope-1"] })
  await mount(page, { seed: JSON.stringify({ version: 1, ids: ["web-01"] }) })
  await expect(favorite(page, "web-01")).toHaveAttribute("aria-pressed", "true")
  await page.evaluate((value) => { window.localStorage.setItem("folio:favorites:v1", value); window.dispatchEvent(new StorageEvent("storage", { key: "folio:favorites:v1", newValue: value })) }, raw)
  await expect(favorite(page, "web-02")).toHaveAttribute("aria-pressed", "true")
  await expect(favorite(page, "web-01")).toHaveAttribute("aria-pressed", "false")
  expect(await stored(page)).toBe(raw)
  await page.evaluate(() => { window.dispatchEvent(new StorageEvent("storage", { key: "drugi-kljuc", newValue: JSON.stringify({ version: 1, ids: ["web-03"] }) })) })
  await expect(favorite(page, "web-03")).toHaveAttribute("aria-pressed", "false")
  await page.evaluate(() => { window.dispatchEvent(new StorageEvent("storage", { key: "folio:favorites:v1", newValue: null })) })
  await expect(favorite(page, "web-02")).toHaveAttribute("aria-pressed", "false")
  expect(await stored(page)).toBe(raw)
})

