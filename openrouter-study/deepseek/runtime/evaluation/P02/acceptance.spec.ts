test('E04: vsi prehodi, tudi enako stanje, po ena zahteva in ohranitev drugih polj [R05,R06,R09,R12]', async ({ page, request, transport }) => {
  for (const target of ['todo', 'in_progress', 'done'] as TaskStatus[]) {
    await page.goto('about:blank')
    await reset(request)
    const before = await snapshot(request)
    const callStart = transport.calls.length
    await page.goto('/#/projects/web?view=board')
    const form = controls(page)
    await form.all.check()
    await form.target.selectOption(target)
    await form.apply.click()
    await summary(page, 3, 0)
    const after = await onlyStatuses(request, before, ['web-01', 'web-02', 'web-03'], target)
    expect(after.saveRequests).toBe(3)
    const expected = before.tasks.filter((task) => task.projectId === 'web').map((task) => ({ id: task.id, body: { title: task.title, status: target } }))
    expect(transport.calls.slice(callStart).sort((a, b) => a.id.localeCompare(b.id))).toEqual(expected)
    await presentation(page, after.tasks, 'web', 'board')
    await expect(form.target).toHaveValue('')
    await expect(form.count).toHaveText('Izbrano: 0')
    await expect(page.getByRole('alert')).toHaveCount(0)
  }
})

