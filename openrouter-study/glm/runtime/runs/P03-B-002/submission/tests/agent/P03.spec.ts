import type { Page } from '@playwright/test'
import { board, click, columnIds, details, expect, expectIds, makeTask, mount, project, readonly, select, summary, table, test, webIds } from '../development/helpers.ts'

const search = (page: Page) => page.getByRole('searchbox', { name: 'Išči opravila' })
const statusFilter = (page: Page) => page.getByRole('combobox', { name: 'Filter stanja' })
const assigneeFilter = (page: Page) => page.getByRole('combobox', { name: 'Filter odgovorne osebe' })
const resultStatus = (page: Page) => page.getByRole('status', { name: 'Rezultati filtriranja' })

test('search is normalized, literal and order independent', async ({ page }) => {
  const writes = await mount(page)
  await expectIds(page, webIds())
  await search(page).fill('ČAS')
  await expectIds(page, ['web-01'])
  await search(page).fill('cas')
  await expectIds(page, ['web-01'])
  await search(page).fill('Zapis, "citat"')
  await expectIds(page, ['web-06'])
  await search(page).fill('Novak pregled')
  await expectIds(page, ['web-01', 'web-03'])
  await search(page).fill('   ')
  await expectIds(page, webIds())
  await readonly(page, writes)
})

test('combined filters persist across views and reset in one action', async ({ page }) => {
  const writes = await mount(page)
  await expect.poll(async () => await assigneeFilter(page).locator('option').evaluateAll(options => options.map(option => option.getAttribute('value') ?? ''))).toEqual(['all', 'Ana Novak', 'Luka Kovač', 'Maja Zupan', 'Živa Kovač', 'Črt'])
  await select(page, 'Filter stanja', 'done')
  await select(page, 'Filter odgovorne osebe', 'Ana Novak')
  await expectIds(page, ['web-03'])
  await expect(resultStatus(page)).toHaveText('Prikazano: 1 od 8.')
  await summary(page, [0, 0, 1])
  await board(page)
  await expectIds(page, ['web-03'])
  await columnIds(page, 'Pripravljeno', [])
  await columnIds(page, 'V delu', [])
  await columnIds(page, 'Končano', ['web-03'])
  await table(page)
  await expectIds(page, ['web-03'])
  await search(page).fill('alfa')
  await select(page, 'Filter stanja', 'todo')
  await select(page, 'Filter odgovorne osebe', 'Maja Zupan')
  await expectIds(page, ['web-04'])
  await summary(page, [1, 0, 0])
  await board(page)
  await expectIds(page, ['web-04'])
  await search(page).fill('neobstoje')
  await expectIds(page, [])
  await expect(page.getByText('Ni zadetkov.', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Tabla', exact: true })).toBeEnabled()
  await table(page)
  await expect(page.getByText('Ni zadetkov.', { exact: true })).toBeVisible()
  await click(page, 'Počisti filtre')
  await expect(search(page)).toHaveValue('')
  await expect(statusFilter(page)).toHaveValue('all')
  await expect(assigneeFilter(page)).toHaveValue('all')
  await expectIds(page, webIds())
  await readonly(page, writes)
})

test('project switch and page refresh reset local filters only', async ({ page }) => {
  const writes = await mount(page)
  await search(page).fill('alfa')
  await select(page, 'Filter stanja', 'done')
  await select(page, 'Filter odgovorne osebe', 'Maja Zupan')
  await project(page, 'launch')
  await expect(search(page)).toHaveValue('')
  await expect(statusFilter(page)).toHaveValue('all')
  await expect(assigneeFilter(page)).toHaveValue('all')
  await expectIds(page, ['launch-01', 'launch-02'])
  await project(page, 'web')
  await search(page).fill('alfa')
  await select(page, 'Filter stanja', 'in_progress')
  await select(page, 'Filter odgovorne osebe', 'Maja Zupan')
  await page.reload()
  await expect(search(page)).toHaveValue('')
  await expect(statusFilter(page)).toHaveValue('all')
  await expect(assigneeFilter(page)).toHaveValue('all')
  await expectIds(page, webIds())
  await expect(page).toHaveURL(/#\/projects\/web$/)
  expect(await page.evaluate(() => localStorage.length)).toBe(0)
  await readonly(page, writes)
})

test('empty projects keep useful views and counters', async ({ page }) => {
  await mount(page, [])
  await expect(resultStatus(page)).toHaveText('Prikazano: 0 od 0.')
  await expect(page.getByRole('heading', { name: 'V tem projektu še ni opravil' })).toBeVisible()
  await board(page)
  await expect(page.getByRole('region', { name: 'Tabla opravil' })).toBeVisible()
  await columnIds(page, 'Pripravljeno', [])
  await columnIds(page, 'V delu', [])
  await columnIds(page, 'Končano', [])
})

test('large projects keep source order and counters', async ({ page }) => {
  const records = Array.from({ length: 11 }, (_, index) => makeTask(`many-${String(index + 1).padStart(2, '0')}`, { title: `Opravilo ${index + 1}`, description: 'Dolg opis' }))
  await mount(page, records)
  await expectIds(page, records.map((task) => task.id))
  await expect(resultStatus(page)).toHaveText('Prikazano: 11 od 11.')
  await search(page).fill('10')
  await expectIds(page, ['many-10'])
})

test('narrow layout keeps navigation and read-only details usable', async ({ page }) => {
  const writes = await mount(page)
  await page.setViewportSize({ width: 390, height: 844 })
  await search(page).fill('Pregled')
  await select(page, 'Filter stanja', 'done')
  await expectIds(page, ['web-03'])
  await readonly(page, writes)
  await details(page, 'web-03')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
})
