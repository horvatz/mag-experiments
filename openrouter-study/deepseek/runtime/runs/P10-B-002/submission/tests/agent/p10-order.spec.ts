test('R04/R05/R06: undo/redo stacks, redo cleared by new move, boundary keeps redo', async ({ page }) => {
  await mount(page)
  await click(page, 'Premakni web-02 gor')
  await click(page, 'Premakni web-03 gor')
  await expectIds(page, ['web-02', 'web-03', 'web-01', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'])
  await expect(history(page)).toHaveText('Razveljavitve: 2. Ponovitve: 0.')
  await click(page, 'Razveljavi premik')
  await expectIds(page, ['web-02', 'web-01', 'web-03', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'])
  await expect(history(page)).toHaveText('Razveljavitve: 1. Ponovitve: 1.')
  await click(page, 'Razveljavi premik')
  await expectIds(page, ['web-01', 'web-02', 'web-03', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'])
  await expect(history(page)).toHaveText('Razveljavitve: 0. Ponovitve: 2.')
  await click(page, 'Ponovi premik')
  await expect(history(page)).toHaveText('Razveljavitve: 1. Ponovitve: 1.')
  await click(page, 'Razveljavi premik')
  await expectIds(page, ['web-01', 'web-02', 'web-03', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'])
  await expect(page.getByRole('button', { name: 'Premakni web-01 gor', exact: true })).toBeDisabled()
  await expect(history(page)).toHaveText('Razveljavitve: 0. Ponovitve: 2.')
  await expect(page.getByRole('button', { name: 'Ponovi premik', exact: true })).toBeEnabled()
  await click(page, 'Ponovi premik')
  await expectIds(page, ['web-02', 'web-01', 'web-03', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'])
  await click(page, 'Razveljavi premik')
  await click(page, 'Premakni web-03 gor')
  await expectIds(page, ['web-01', 'web-03', 'web-02', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'])
  await expect(page.getByRole('button', { name: 'Ponovi premik', exact: true })).toBeDisabled()
  await expect(history(page)).toHaveText('Razveljavitve: 1. Ponovitve: 0.')
})

test('R07: undo history keeps at most 20 previous permutations', async ({ page }) => {
  await mount(page)
  for (let index = 0; index < 10; index += 1) {
    await click(page, 'Premakni web-02 gor')
    await click(page, 'Premakni web-02 dol')
  }
  await click(page, 'Premakni web-03 gor')
  await expect(history(page)).toHaveText('Razveljavitve: 20. Ponovitve: 0.')
  for (let index = 0; index < 20; index += 1) await click(page, 'Razveljavi premik')
  await expect(page.getByRole('button', { name: 'Razveljavi premik', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Ponovi premik', exact: true })).toBeEnabled()
  await expect(history(page)).toHaveText('Razveljavitve: 0. Ponovitve: 20.')
  await expectIds(page, ['web-02', 'web-01', 'web-03', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'])
  expect([...new Set(await ids(page))].length).toBe(8)
})

test('R08/R09/R10: reset is one action, board uses global neighbours, state survives views/details', async ({ page }) => {
  await mount(page)
  await click(page, 'Premakni web-02 gor')
  await click(page, 'Premakni web-03 gor')
  await expectIds(page, ['web-02', 'web-03', 'web-01', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'])
  await board(page)
  await expect(rank(page, 'web-02')).toHaveText('1')
  await click(page, 'Premakni web-04 gor')
  await expect(rank(page, 'web-04')).toHaveText('3')
  await expect(rank(page, 'web-03')).toHaveText('2')
  await columnIds(page, 'Pripravljeno', ['web-02', 'web-04', 'web-07', 'web-08'])
  await columnIds(page, 'Končano', ['web-03', 'web-06'])
  await summary(page, [4, 2, 2])
  await details(page, 'web-02')
  await expect(rank(page, 'web-02')).toHaveText('1')
  await expect(history(page)).toHaveText('Razveljavitve: 3. Ponovitve: 0.')
  await table(page)
  await expectIds(page, ['web-02', 'web-03', 'web-04', 'web-01', 'web-05', 'web-06', 'web-07', 'web-08'])
  await expect(page.locator('[data-task-id="web-04"]').getByText('Pripravljeno', { exact: true })).toBeVisible()
  await expect(page.locator('[data-task-id="web-03"]').getByText('Končano', { exact: true })).toBeVisible()
  await click(page, 'Začetni vrstni red')
  await expectIds(page, ['web-01', 'web-02', 'web-03', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'])
  await expect(page.getByRole('button', { name: 'Začetni vrstni red', exact: true })).toBeDisabled()
  await expect(history(page)).toHaveText('Razveljavitve: 4. Ponovitve: 0.')
  await click(page, 'Razveljavi premik')
  await expectIds(page, ['web-02', 'web-03', 'web-04', 'web-01', 'web-05', 'web-06', 'web-07', 'web-08'])
  await project(page, 'launch')
  await expect(history(page)).toHaveText('Razveljavitve: 0. Ponovitve: 0.')
  await expect(rank(page, 'launch-01')).toHaveText('1')
  await project(page, 'web')
  await expectIds(page, ['web-01', 'web-02', 'web-03', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'])
  await click(page, 'Premakni web-02 gor')
  await page.reload()
  await expectIds(page, ['web-01', 'web-02', 'web-03', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'])
  await expect(history(page)).toHaveText('Razveljavitve: 0. Ponovitve: 0.')
})

