import type { Page } from '@playwright/test'
import { test, expect, mount, expectIds, ids, select, click, board, table, details, project, readonly, summary, makeTask, examples, type Task } from '../development/helpers.ts'

const many: Task[] = Array.from({ length: 11 }, (_, index) => makeTask(`task-${String(index + 1).padStart(2, '0')}`, {
  title: index === 3 ? 'Ponovljen naslov' : `Opravilo ${index + 1}`,
  status: (index + 1) % 3 === 0 ? 'done' : (index + 1) % 3 === 1 ? 'todo' : 'in_progress',
}))
const manyIds = many.map((task) => task.id)
const status = (page: Page) => page.getByRole('status', { name: 'Stanje straničenja' })
const buttons = (page: Page) => ['Prva stran', 'Prejšnja stran', 'Naslednja stran', 'Zadnja stran'].map((name) => page.getByRole('button', { name, exact: true }))

async function collectPages(page: Page, size: string) {
  await select(page, 'Velikost strani', size)
  const pages: string[][] = []
  for (;;) {
    pages.push((await ids(page)).map((id) => id ?? ''))
    const next = page.getByRole('button', { name: 'Naslednja stran', exact: true })
    if (await next.isDisabled()) break
    await next.click()
  }
  return pages
}

test('A01: privzeto all/all v izvornem vrstnem redu', async ({ page }) => {
  await mount(page, many)
  await expectIds(page, manyIds)
  await expect(page.getByRole('combobox', { name: 'Velikost strani' })).toHaveValue('all')
  await expect(page.getByRole('combobox', { name: 'Filter strani' })).toHaveValue('all')
  await expect(status(page)).toHaveText('Stran 1 od 1. Prikazano 1–11 od 11.')
  await expect(page.locator('.count-badge')).toHaveText('11')
})

test('A02: velikosti 2/5/10 tvorijo zaporedne odseke brez izgub in podvajanj', async ({ page }) => {
  await mount(page, many)
  for (const [size, expectedPages] of [['2', 6], ['5', 3], ['10', 2]] as const) {
    const pages = await collectPages(page, size)
    expect(pages.length).toBe(expectedPages)
    expect(pages.flat()).toEqual(manyIds)
    expect(new Set(pages.flat()).size).toBe(manyIds.length)
    for (const slice of pages.slice(0, -1)) expect(slice.length).toBe(Number(size))
    expect(pages.at(-1)!.length).toBe(manyIds.length % Number(size) || Number(size))
  }
  await select(page, 'Velikost strani', '5')
  await click(page, 'Zadnja stran')
  await expect(status(page)).toHaveText('Stran 3 od 3. Prikazano 11–11 od 11.')
})

test('A03: robovi strani onemogočijo neveljavna dejanja', async ({ page }) => {
  await mount(page, many)
  await select(page, 'Velikost strani', '5')
  const [first, previous, next, last] = buttons(page)
  await expect(first).toBeDisabled()
  await expect(previous).toBeDisabled()
  await expect(next).toBeEnabled()
  await expect(last).toBeEnabled()
  await click(page, 'Zadnja stran')
  await expect(status(page)).toHaveText('Stran 3 od 3. Prikazano 11–11 od 11.')
  await expect(next).toBeDisabled()
  await expect(last).toBeDisabled()
  await expect(first).toBeEnabled()
  await expect(previous).toBeEnabled()
  await click(page, 'Prva stran')
  await expect(status(page)).toHaveText('Stran 1 od 3. Prikazano 1–5 od 11.')
  await expectIds(page, manyIds.slice(0, 5))
})

