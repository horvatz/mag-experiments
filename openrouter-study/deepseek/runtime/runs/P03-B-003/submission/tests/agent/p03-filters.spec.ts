test('general rules hold for a 13-task project with Unicode names', async ({ page }) => {
  const many = Array.from({ length: 12 }, (_, index) => makeTask(`t-${String(index + 1).padStart(2, '0')}`, {
    title: index % 2 === 0 ? 'Naloga' : 'Opravilo',
    status: (['todo', 'in_progress', 'done'] as const)[index % 3],
    assignee: index % 4 === 0 ? 'Ana Novak' : 'Éva Črnič',
    description: `Opis ${index}`,
  }))
  many.push(makeTask('t-13', { title: 'Samo eno', status: 'done', assignee: 'Žan' }))
  await mount(page, many)
  await expect(statusText(page)).toHaveText('Prikazano: 13 od 13.')
  await summary(page, [4, 4, 5])
  await search(page).fill('naloga')
  await expect(statusText(page)).toHaveText('Prikazano: 6 od 13.')
  await summary(page, [2, 2, 2])
  await search(page).fill('crnic eva')
  await expect(statusText(page)).toHaveText('Prikazano: 9 od 13.')
  await select(page, 'Filter odgovorne osebe', 'Éva Črnič')
  await expect(statusText(page)).toHaveText('Prikazano: 9 od 13.')
  await search(page).fill('')
  await select(page, 'Filter odgovorne osebe', 'Ana Novak')
  await expectIds(page, ['t-01', 't-05', 't-09'])
  await click(page, 'Počisti filtre')
  await expect(statusText(page)).toHaveText('Prikazano: 13 od 13.')
})
