import { expect, test, mount, click, ids, expectIds, board, table, project, details, readonly, summary, columnIds, makeTask } from '../development/helpers.ts'

const rank = (page: import('@playwright/test').Page, id: string) => page.getByLabel(`Mesto opravila ${id}`, { exact: true })
const history = (page: import('@playwright/test').Page) => page.getByRole('status', { name: 'Zgodovina vrstnega reda' })

test('R01/R11: initial order, ranks, duplicate titles, empty and single-task projects', async ({ page }) => {
  const writes = await mount(page)
  await expectIds(page, ['web-01', 'web-02', 'web-03', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'])
  for (const [index, id] of ['web-01', 'web-02', 'web-03', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'].entries()) {
    await expect(rank(page, id)).toHaveText(String(index + 1))
  }
  await expect(page.locator('[data-task-id="web-02"]').getByText('Pregled vsebine', { exact: true })).toBeVisible()
  await expect(page.locator('[data-task-id="web-03"]').getByText('Pregled vsebine', { exact: true })).toBeVisible()
  await expect(history(page)).toHaveText('Razveljavitve: 0. Ponovitve: 0.')
  await expect(page.getByRole('button', { name: 'Razveljavi premik', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Ponovi premik', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Začetni vrstni red', exact: true })).toBeDisabled()
  await summary(page, [4, 2, 2])
  await readonly(page, writes)

  await mount(page, [])
  await page.reload()
  await expect(page.getByRole('heading', { name: 'V tem projektu še ni opravil' })).toBeVisible()
  await expect(page.getByRole('button', { name: /^Premakni / })).toHaveCount(0)
  await expect(history(page)).toHaveText('Razveljavitve: 0. Ponovitve: 0.')
  await expect(page.getByRole('button', { name: 'Razveljavi premik', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Ponovi premik', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Začetni vrstni red', exact: true })).toBeDisabled()

  await mount(page, [makeTask('web-01')])
  await page.reload()
  await expect(page.getByRole('button', { name: 'Premakni web-01 gor', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Premakni web-01 dol', exact: true })).toBeDisabled()
  await expect(history(page)).toHaveText('Razveljavitve: 0. Ponovitve: 0.')
  await expect(rank(page, 'web-01')).toHaveText('1')
})

