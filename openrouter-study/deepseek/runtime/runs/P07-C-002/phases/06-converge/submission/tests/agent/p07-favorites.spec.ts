test("P07-R03: obnova strne dvojnike in ohrani neznane", async ({ page }) => {
  await mount(page, { seed: JSON.stringify({ version: 1, ids: ["web-02", "web-02", "nope-1", "web-01"] }) })
  await expect(favorite(page, "web-02")).toHaveAttribute("aria-pressed", "true")
  await expect(favorite(page, "web-01")).toHaveAttribute("aria-pressed", "true")
  await expectIds(page, webIds)
  await page.reload()
  await expect(favorite(page, "web-02")).toHaveAttribute("aria-pressed", "true")
  await favorite(page, "web-02").click()
  expect(JSON.parse((await stored(page))!)).toEqual({ version: 1, ids: ["nope-1", "web-01"] })
})

test("P07-R04: neveljavni zapisi pomenijo prazno množico brez prepisa", async ({ page }) => {
  await mount(page)
  const invalid: (string | null)[] = [null, "ni json", JSON.stringify({ version: 2, ids: ["web-01"] }), JSON.stringify({ version: 1 }), JSON.stringify({ version: 1, ids: ["web-01", 5] })]
  for (const payload of invalid) {
    await page.evaluate((value) => { if (value === null) window.localStorage.removeItem("folio:favorites:v1"); else window.localStorage.setItem("folio:favorites:v1", value) }, payload)
    const before = await stored(page)
    await page.reload()
    await expect(page.getByRole("heading", { level: 1 })).toBeVisible()
    await expect(favorite(page, "web-01")).toBeVisible()
    await expect(page.locator(".favorite-button[aria-pressed=true]")).toHaveCount(0)
    expect(await stored(page)).toBe(before)
  }
})

