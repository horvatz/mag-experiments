test('R06: preglednica in tabla kažeta isti odsek', async ({ page }) => {
  await mount(page)
  await select(page, 'Velikost strani', '2')
  await click(page, 'Naslednja stran')
  await expectIds(page, ['web-03', 'web-04'])
  await board(page)
  const shown = (await ids(page)).sort()
  expect(shown).toEqual(['web-03', 'web-04'])
  await expect(page.getByRole('region', { name: 'Pripravljeno', exact: true }).locator('[data-task-id]')).toHaveCount(1)
  await expect(page.getByRole('region', { name: 'Končano', exact: true }).locator('[data-task-id]')).toHaveCount(1)
  await expect(page.getByRole('region', { name: 'V delu', exact: true }).locator('[data-task-id]')).toHaveCount(0)
  expect(await columnCounts(page)).toEqual([1, 0, 1])
  await table(page)
  await expectIds(page, ['web-03', 'web-04'])
})

