test('A14: the page does not overflow at 390px with filters applied (R12)', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await mount(page)
  await search(page).fill('web-0')
  await select(page, 'Filter stanja', 'done')
  await expect(resultStatus(page)).toHaveText('Prikazano: 2 od 8.')
  await expect(resultStatus(page)).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const scroll = page.locator('.table-scroll')
  expect(await scroll.evaluate((node) => node.scrollWidth > node.clientWidth)).toBe(true)
  await board(page)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await click(page, 'Počisti filtre')
  // V tabli so kartice razvrscene po stolpcih, zato vrstni red ni izvorni.
  await expectIds(page, webIds(), false)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

