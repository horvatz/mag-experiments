import type { Page } from '@playwright/test'
import { expect, test, mount, expectIds, webIds, board, table, select, click, project, details, readonly, summary, columnIds } from '../development/helpers.ts'

const searchBox = (page: Page) => page.getByRole('searchbox', { name: 'Išči opravila' })
const results = (page: Page) => page.getByRole('status', { name: 'Rezultati filtriranja' })
const statusSelect = (page: Page) => page.getByRole('combobox', { name: 'Filter stanja', exact: true })
const assigneeSelect = (page: Page) => page.getByRole('combobox', { name: 'Filter odgovorne osebe', exact: true })

test('R01, R09: privzeto stanje prikaže vsa opravila v izvornem vrstnem redu', async ({ page }) => {
  await mount(page)
  await expectIds(page, webIds())
  await expect(searchBox(page)).toHaveValue('')
  await expect(statusSelect(page)).toHaveValue('all')
  await expect(assigneeSelect(page)).toHaveValue('all')
  await expect(results(page)).toHaveText('Prikazano: 8 od 8.')
  await summary(page, [4, 2, 2])
})

test('R02, R03: iskanje normalizira črke, deli po belinah in bere ločila dobesedno', async ({ page }) => {
  await mount(page)
  await searchBox(page).fill('CAS')
  await expectIds(page, ['web-01'])
  await searchBox(page).fill('CRT')
  await expectIds(page, ['web-07'])
  await searchBox(page).fill('pregled vsebine')
  await expectIds(page, ['web-01', 'web-02', 'web-03'])
  await searchBox(page).fill('vsebine pregled')
  await expectIds(page, ['web-01', 'web-02', 'web-03'])
  await searchBox(page).fill('druga vrstica')
  await expectIds(page, ['web-06'])
  await searchBox(page).fill('"citat"')
  await expectIds(page, ['web-06'])
  await searchBox(page).fill('=SUM(A1)')
  await expectIds(page, ['web-07'])
  await searchBox(page).fill('kovač')
  await expectIds(page, ['web-02', 'web-06'])
  await searchBox(page).fill('   ')
  await expectIds(page, webIds())
})

test('R04, R05: filtri se vežejo z IN, možnosti oseb pa ostanejo iz celotnega projekta', async ({ page }) => {
  await mount(page)
  const optionValues = () => assigneeSelect(page).locator('option').evaluateAll((nodes) => nodes.map((node) => (node as HTMLOptionElement).value))
  const expected = ['Ana Novak', 'Luka Kovač', 'Maja Zupan', 'Živa Kovač', 'Črt'].sort()
  const values = await optionValues()
  expect(values[0]).toBe('all')
  expect([...values.slice(1)].sort()).toEqual(expected)
  await select(page, 'Filter stanja', 'done')
  await select(page, 'Filter odgovorne osebe', 'Ana Novak')
  await expectIds(page, ['web-03'])
  await expect(results(page)).toHaveText('Prikazano: 1 od 8.')
  await summary(page, [0, 0, 1])
  expect([...(await optionValues()).slice(1)].sort()).toEqual(expected)
  await select(page, 'Filter odgovorne osebe', 'Črt')
  await expectIds(page, [])
  await expect(results(page)).toHaveText('Prikazano: 0 od 8.')
  await select(page, 'Filter stanja', 'all')
  await expectIds(page, ['web-07'])
})

test('R06: oba pogleda kažeta iste filtrirane ID-je, stolpci pa svoje stanje', async ({ page }) => {
  await mount(page)
  await searchBox(page).fill('pregled')
  await select(page, 'Filter stanja', 'todo')
  await expectIds(page, ['web-02'])
  await board(page)
  await expectIds(page, ['web-02'])
  await columnIds(page, 'Pripravljeno', ['web-02'])
  await columnIds(page, 'V delu', [])
  await columnIds(page, 'Končano', [])
  await table(page)
  await expectIds(page, ['web-02'])
  await expect(searchBox(page)).toHaveValue('pregled')
  await expect(statusSelect(page)).toHaveValue('todo')
})

test('R07, R08: menjava projekta in osvežitev ponastavita filtre, URL ostane brez njih', async ({ page }) => {
  await mount(page)
  await searchBox(page).fill('pregled')
  await select(page, 'Filter stanja', 'done')
  expect(new URL(page.url()).hash).toBe('#/projects/web')
  await project(page, 'launch')
  await expect(searchBox(page)).toHaveValue('')
  await expect(statusSelect(page)).toHaveValue('all')
  await expect(assigneeSelect(page)).toHaveValue('all')
  await expectIds(page, ['launch-01', 'launch-02'])
  await expect(results(page)).toHaveText('Prikazano: 2 od 2.')
  await searchBox(page).fill('drugi')
  await expectIds(page, ['launch-01', 'launch-02'])
  await page.reload()
  await expect(searchBox(page)).toHaveValue('')
  await expect(results(page)).toHaveText('Prikazano: 2 od 2.')
  await expectIds(page, ['launch-01', 'launch-02'])
})

test('R10: ni zadetkov ohrani oba pogleda uporabna, prazen projekt pa običajno stanje', async ({ page }) => {
  await mount(page)
  await searchBox(page).fill('neobstojece')
  await expect(page.getByText('Ni zadetkov.', { exact: true })).toBeVisible()
  await expect(results(page)).toHaveText('Prikazano: 0 od 8.')
  await expect(page.getByRole('table')).toHaveCount(0)
  await board(page)
  await expect(page.getByRole('region', { name: 'Tabla opravil', exact: true })).toBeVisible()
  await expect(page.locator('[data-task-id]')).toHaveCount(0)
  await expect(page.getByText('Ni zadetkov.', { exact: true })).toBeVisible()
  await click(page, 'Počisti filtre')
  await expectIds(page, webIds(), false)
  await table(page)
  await expectIds(page, webIds())
})

test('R10: prazen projekt ohrani prazno stanje in števec 0 od 0', async ({ page }) => {
  await mount(page, [])
  await expect(results(page)).toHaveText('Prikazano: 0 od 0.')
  await expect(page.getByRole('heading', { name: 'V tem projektu še ni opravil' })).toBeVisible()
  await board(page)
  await expect(page.getByRole('region', { name: 'Tabla opravil', exact: true })).toBeVisible()
  await table(page)
  await expect(page.getByRole('heading', { name: 'V tem projektu še ni opravil' })).toBeVisible()
})

test('R11, R12: čiščenje filtrov, podrobnosti in branje brez pisanja na API', async ({ page }) => {
  const writes = await mount(page)
  await searchBox(page).fill('pregled')
  await select(page, 'Filter stanja', 'done')
  await select(page, 'Filter odgovorne osebe', 'Ana Novak')
  await expectIds(page, ['web-03'])
  await details(page, 'web-03')
  await click(page, 'Počisti filtre')
  await expect(searchBox(page)).toHaveValue('')
  await expect(statusSelect(page)).toHaveValue('all')
  await expect(assigneeSelect(page)).toHaveValue('all')
  await expectIds(page, webIds())
  await readonly(page, writes)
})

test('R12: pri ozki širini se stran ne razširi z aktivnimi filtri', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await mount(page)
  await searchBox(page).fill('pregled')
  await expectIds(page, ['web-01', 'web-02', 'web-03'])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  await board(page)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
})
