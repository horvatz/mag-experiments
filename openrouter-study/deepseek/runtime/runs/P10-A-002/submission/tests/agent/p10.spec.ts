test('R09: tabla ohrani relativni red, premiki uporabijo globalno mesto', async ({ page }) => {
  await mount(page)
  await board(page)
  await expect(position(page, 'web-02')).toHaveText('2')
  await click(page, 'Premakni web-03 gor')
  await expect(position(page, 'web-03')).toHaveText('2')
  await expect(position(page, 'web-02')).toHaveText('3')
  await expect(page.getByRole('region', { name: 'Končano', exact: true }).locator('[data-task-id="web-03"]')).toBeVisible()
  const todo = page.getByRole('region', { name: 'Pripravljeno', exact: true }).locator('[data-task-id]')
  await expect.poll(() => todo.evaluateAll((nodes) => nodes.map((node) => node.getAttribute('data-task-id')))).toEqual(['web-02', 'web-04', 'web-07', 'web-08'])
  await table(page)
  await expectIds(page, ['web-01', 'web-03', 'web-02', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'])
})

test('R10: pogled, podrobnosti, menjava projekta in osvezitev', async ({ page }) => {
  await mount(page)
  await click(page, 'Premakni web-02 gor')
  await board(page)
  await expect(position(page, 'web-02')).toHaveText('1')
  await page.locator('[data-task-id="web-02"]').getByRole('link').click()
  await expect(page.getByRole('dialog')).toContainText('Pregled vsebine')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(position(page, 'web-02')).toHaveText('1')
  await expect(history(page)).toHaveText('Razveljavitve: 1. Ponovitve: 0.')
  await table(page)
  await expectIds(page, ['web-02', 'web-01', 'web-03', 'web-04', 'web-05', 'web-06', 'web-07', 'web-08'])
  await project(page, 'launch')
  await expectIds(page, ['launch-01', 'launch-02'])
  await expect(history(page)).toHaveText('Razveljavitve: 0. Ponovitve: 0.')
  await project(page, 'web')
  await expectIds(page, webIds())
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Spletna prenova', exact: true })).toBeVisible()
  await expectIds(page, webIds())
  await expect(history(page)).toHaveText('Razveljavitve: 0. Ponovitve: 0.')
})

