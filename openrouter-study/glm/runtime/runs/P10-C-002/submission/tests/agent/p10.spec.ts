import { test, expect, type Page } from '@playwright/test'
import { mount, expectIds, webIds, click, board, details, readonly, columnIds, summary, makeTask } from '../development/helpers.ts'

const history = (page: Page) => page.getByRole('status', { name: 'Zgodovina vrstnega reda' })

test('agent P10: initial order, ranks, duplicate titles and a valid move preserve task data', async ({ page }) => {
  const writes = await mount(page)
  await expect(history(page)).toHaveText('Razveljavitve: 0. Ponovitve: 0.')
  await expectIds(page, webIds())
  await expect(page.getByRole('link', { name: 'Pregled vsebine web-02' })).toHaveAttribute('href', '#/projects/web/tasks/web-02')
  await expect(page.getByRole('link', { name: 'Pregled vsebine web-03' })).toHaveAttribute('href', '#/projects/web/tasks/web-03')
  await click(page, 'Premakni web-02 gor')
  await expectIds(page, [webIds()[1], webIds()[0], ...webIds().slice(2)])
  await expect(page.getByLabel('Mesto opravila web-02', { exact: true })).toHaveText('1')
  await expect(page.getByLabel('Mesto opravila web-01', { exact: true })).toHaveText('2')
  const row = page.locator('[data-task-id="web-02"]')
  await expect(row.getByRole('link')).toContainText('Pregled vsebine')
  await expect(row.getByText('Pripravljeno', { exact: true })).toBeVisible()
  await expect(row.getByText('Luka Kovač')).toBeVisible()
  await expect(row.getByText('22. sep. 2026')).toBeVisible()
  await summary(page, [4, 2, 2])
  await readonly(page, writes)
})

test('agent P10: boundaries and repeated invalid actions do not add history', async ({ page }) => {
  const writes = await mount(page)
  await expect(page.getByRole('button', { name: 'Premakni web-01 gor', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: `Premakni ${webIds().at(-1)} dol`, exact: true })).toBeDisabled()
  await click(page, 'Premakni web-02 gor')
  await expect(history(page)).toHaveText('Razveljavitve: 1. Ponovitve: 0.')
  await click(page, 'Razveljavi premik')
  await expect(page.getByRole('button', { name: 'Premakni web-01 gor', exact: true })).toBeDisabled()
  await expect(history(page)).toHaveText('Razveljavitve: 0. Ponovitve: 1.')
  await click(page, 'Premakni web-03 gor')
  await expect(page.getByRole('button', { name: 'Ponovi premik', exact: true })).toBeDisabled()
  await expect(history(page)).toHaveText('Razveljavitve: 1. Ponovitve: 0.')
  await readonly(page, writes)
})

test('agent P10: multiple undo and redo sequences stay consistent', async ({ page }) => {
  const writes = await mount(page)
  await click(page, 'Premakni web-02 gor')
  await expect(history(page)).toHaveText('Razveljavitve: 1. Ponovitve: 0.')
  await click(page, 'Premakni web-03 gor')
  await expect(history(page)).toHaveText('Razveljavitve: 2. Ponovitve: 0.')
  await expectIds(page, [webIds()[1], webIds()[2], webIds()[0], ...webIds().slice(3)])
  await click(page, 'Razveljavi premik')
  await expect(history(page)).toHaveText('Razveljavitve: 1. Ponovitve: 1.')
  await click(page, 'Razveljavi premik')
  await expect(history(page)).toHaveText('Razveljavitve: 0. Ponovitve: 2.')
  await expectIds(page, webIds())
  await click(page, 'Ponovi premik')
  await expect(history(page)).toHaveText('Razveljavitve: 1. Ponovitve: 1.')
  await click(page, 'Ponovi premik')
  await expect(history(page)).toHaveText('Razveljavitve: 2. Ponovitve: 0.')
  await expectIds(page, [webIds()[1], webIds()[2], webIds()[0], ...webIds().slice(3)])
  await click(page, 'Razveljavi premik')
  await expect(history(page)).toHaveText('Razveljavitve: 1. Ponovitve: 1.')
  await click(page, 'Premakni web-04 gor')
  await expect(history(page)).toHaveText('Razveljavitve: 2. Ponovitve: 0.')
  await expectIds(page, [webIds()[1], webIds()[0], webIds()[3], webIds()[2], ...webIds().slice(4)])
  await readonly(page, writes)
})

test('agent P10: undo history keeps at most twenty and redo covers all undone steps', async ({ page }) => {
  const writes = await mount(page)
  for (let index = 0; index < 21; index++) {
    await click(page, index % 2 === 0 ? 'Premakni web-02 dol' : 'Premakni web-02 gor')
    await expect(history(page)).toHaveText(`Razveljavitve: ${index + 1}. Ponovitve: 0.`)
  }
  for (let index = 0; index < 20; index++) {
    await click(page, 'Razveljavi premik')
    await expect(history(page)).toHaveText(`Razveljavitve: ${20 - index}. Ponovitve: ${index + 1}.`)
  }
  for (let index = 0; index < 20; index++) {
    await click(page, 'Ponovi premik')
    await expect(history(page)).toHaveText(`Razveljavitve: ${index + 2}. Ponovitve: ${19 - index}.`)
  }
  await expectIds(page, [webIds()[0], webIds()[2], webIds()[1], ...webIds().slice(3)])
  await readonly(page, writes)
})

test('agent P10: board, view and details preserve local state while reset restores initial order', async ({ page }) => {
  const writes = await mount(page)
  await board(page)
  await click(page, 'Premakni web-02 gor')
  await expect(page.getByLabel('Mesto opravila web-02', { exact: true })).toHaveText('1')
  await columnIds(page, 'Pripravljeno', [webIds()[1], webIds()[3], webIds()[6], webIds()[7]])
  await columnIds(page, 'V delu', [webIds()[0], webIds()[4]])
  await columnIds(page, 'Končano', [webIds()[2], webIds()[5]])
  await expect(history(page)).toHaveText('Razveljavitve: 1. Ponovitve: 0.')
  await page.getByRole('button', { name: 'Preglednica', exact: true }).click()
  await expect(history(page)).toHaveText('Razveljavitve: 1. Ponovitve: 0.')
  await details(page, webIds()[1])
  await expect(history(page)).toHaveText('Razveljavitve: 1. Ponovitve: 0.')
  await click(page, 'Začetni vrstni red')
  await expectIds(page, webIds())
  await expect(history(page)).toHaveText('Razveljavitve: 2. Ponovitve: 0.')
  await click(page, 'Premakni web-02 gor')
  await expect(history(page)).toHaveText('Razveljavitve: 3. Ponovitve: 0.')
  await page.reload()
  await expectIds(page, webIds())
  await expect(history(page)).toHaveText('Razveljavitve: 0. Ponovitve: 0.')
  await readonly(page, writes)
})

