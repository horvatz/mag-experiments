import type { Page } from "@playwright/test"
import { test, expect, mount, expectIds, webIds, select, click, board, table, details, project, readonly, makeTask } from "../development/helpers.ts"

const hash = (page: Page) => page.evaluate(() => window.location.hash)
const historyLength = (page: Page) => page.evaluate(() => history.length)
const counter = (page: Page) => page.getByRole("status", { name: "Rezultati povezave" })
const search = (page: Page) => page.getByRole("searchbox", { name: "Iskanje v povezavi" })
const statusSelect = (page: Page) => page.getByRole("combobox", { name: "Stanje v povezavi" })
const orderSelect = (page: Page) => page.getByRole("combobox", { name: "Vrstni red v povezavi" })

test("R01/R04: direct links parse parameters, defaults and first occurrence", async ({ page }) => {
  await mount(page, undefined, "#/projects/web?q=pregled&status=done")
  await expectIds(page, ["web-03"])
  await expect(search(page)).toHaveValue("pregled")
  await expect(statusSelect(page)).toHaveValue("done")

  await mount(page, undefined, "#/projects/web?status=bogus&order=bogus&extra=1")
  await expectIds(page, webIds())
  await expect(statusSelect(page)).toHaveValue("all")
  await expect(orderSelect(page)).toHaveValue("original")

  await mount(page, undefined, "#/projects/web?status=done&status=todo")
  await expectIds(page, ["web-03", "web-06"])
})

test("R02: q is one literal phrase with NFD normalization", async ({ page }) => {
  await mount(page, undefined, "#/projects/web?q=cas")
  await expectIds(page, ["web-01"])
  await mount(page, undefined, "#/projects/web?q=%C5%BEiva")
  await expectIds(page, ["web-06"])
  await mount(page, undefined, "#/projects/web?q=sum(a1")
  await expectIds(page, ["web-07"])
  await mount(page, undefined, "#/projects/web?q=alfa%202")
  await expectIds(page, ["web-05"])
  await mount(page, undefined, "#/projects/web?q=%20pregled%20")
  await expectIds(page, ["web-01", "web-02", "web-03"])
})

test("R03: q and status combine with AND, title order is stable", async ({ page }) => {
  await mount(page, undefined, "#/projects/web?order=title-asc")
  await expectIds(page, ["web-07", "web-04", "web-05", "web-01", "web-08", "web-02", "web-03", "web-06"])
  await mount(page, undefined, "#/projects/web?order=title-desc")
  await expectIds(page, ["web-06", "web-02", "web-03", "web-08", "web-01", "web-05", "web-04", "web-07"])
  await mount(page, undefined, "#/projects/web?q=pregled&status=done")
  await expectIds(page, ["web-03"])
  const records = [makeTask("t-1", { title: "Enako" }), makeTask("t-2", { title: "enako" }), makeTask("t-3", { title: "Énako" })]
  await mount(page, records, "#/projects/web?order=title-asc")
  await page.reload()
  await expectIds(page, ["t-1", "t-2", "t-3"])
  await mount(page, records, "#/projects/web?order=title-desc")
  await expectIds(page, ["t-1", "t-2", "t-3"])
})

test("R05/R06: draft, atomic apply, one history entry, encoding", async ({ page }) => {
  await mount(page)
  const before = await historyLength(page)
  await select(page, "Stanje v povezavi", "done")
  await expectIds(page, webIds())
  await expect.poll(() => hash(page)).toBe("#/projects/web")
  await click(page, "Uporabi pogled")
  await expectIds(page, ["web-03", "web-06"])
  await expect.poll(() => hash(page)).toContain("status=done")
  expect(await historyLength(page)).toBe(before + 1)
  await click(page, "Uporabi pogled")
  expect(await historyLength(page)).toBe(before + 1)
  await search(page).fill("  pregled  ")
  await click(page, "Uporabi pogled")
  await expect.poll(() => hash(page)).toContain("q=pregled")
  await expect(search(page)).toHaveValue("pregled")
  expect(await historyLength(page)).toBe(before + 2)

  await mount(page, undefined, "#/projects/web?view=board")
  await select(page, "Stanje v povezavi", "done")
  await click(page, "Uporabi pogled")
  await expect(page.getByRole("region", { name: "Tabla opravil" })).toBeVisible()
  await expect.poll(() => hash(page)).toContain("view=board")
  await expect.poll(() => hash(page)).toContain("status=done")
  await expectIds(page, ["web-03", "web-06"])
})

test("R07/R08: back, forward, reload and view switch preserve committed state", async ({ page }) => {
  await mount(page)
  await select(page, "Stanje v povezavi", "done")
  await click(page, "Uporabi pogled")
  await expectIds(page, ["web-03", "web-06"])
  await page.goBack()
  await expectIds(page, webIds())
  await expect(statusSelect(page)).toHaveValue("all")
  await page.goForward()
  await expectIds(page, ["web-03", "web-06"])
  await page.reload()
  await expectIds(page, ["web-03", "web-06"])
  await expect(statusSelect(page)).toHaveValue("done")
  await select(page, "Stanje v povezavi", "todo")
  await board(page)
  await expectIds(page, ["web-03", "web-06"])
  await table(page)
  await expectIds(page, ["web-03", "web-06"])
  await expect(statusSelect(page)).toHaveValue("done")
})

test("R09: details and Escape keep committed parameters and view", async ({ page }) => {
  await mount(page, undefined, "#/projects/web?status=done")
  await details(page, "web-03")
  await expect.poll(() => hash(page)).toContain("status=done")
  await expectIds(page, ["web-03", "web-06"])

  await mount(page, undefined, "#/projects/web?view=board&status=done")
  await details(page, "web-03")
  await expect(page.getByRole("region", { name: "Tabla opravil" })).toBeVisible()
  await expect.poll(() => hash(page)).toContain("view=board")

  await mount(page)
  await page.locator("[data-task-id=\"web-02\"]").getByRole("link").click()
  await expect(page.getByRole("dialog")).toBeVisible()
  await expect(page.getByRole("dialog").getByText("web-02", { exact: true }).first()).toBeVisible()
  await page.getByRole("button", { name: "Zapri podrobnosti" }).click()
  await expect(page.getByRole("dialog")).toHaveCount(0)
  await expect.poll(() => hash(page)).toBe("#/projects/web")
})

