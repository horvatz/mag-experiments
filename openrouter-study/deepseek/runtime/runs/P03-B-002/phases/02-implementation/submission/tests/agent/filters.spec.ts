import { test, expect, mount, expectIds, webIds, select, board, table, click, readonly, summary, project, details } from '../development/helpers.ts'
import type { Task } from '../development/helpers.ts'

const webTaskIds = webIds()

test('R01/R09/R11: defaults, visible counts and clear filters', async ({ page }) => {
  await mount(page)
  await expectIds(page, webTaskIds)
  await expect(page.getByRole('searchbox', { name: 'Išči opravila' })).toHaveValue('')
  await expect(page.getByRole('combobox', { name: 'Filter stanja' })).toHaveValue('all')
  await expect(page.getByRole('combobox', { name: 'Filter odgovorne osebe' })).toHaveValue('all')
  await expect(page.getByRole('status', { name: 'Rezultati filtriranja' })).toHaveText('Prikazano: 8 od 8.')
  await summary(page, [4, 2, 2])
  await page.getByRole('searchbox', { name: 'Išči opravila' }).fill('pregled')
  await select(page, 'Filter stanja', 'done')
  await expectIds(page, ['web-03'])
  await expect(page.getByRole('status', { name: 'Rezultati filtriranja' })).toHaveText('Prikazano: 1 od 8.')
  await summary(page, [0, 0, 1])
  await click(page, 'Počisti filtre')
  await expectIds(page, webTaskIds)
  await expect(page.getByRole('searchbox', { name: 'Išči opravila' })).toHaveValue('')
  await expect(page.getByRole('combobox', { name: 'Filter stanja' })).toHaveValue('all')
  await expect(page.getByRole('combobox', { name: 'Filter odgovorne osebe' })).toHaveValue('all')
})

