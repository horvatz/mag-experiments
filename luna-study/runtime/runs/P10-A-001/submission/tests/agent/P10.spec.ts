import { test, expect, mount, makeTask, webIds, click, board, table, expectIds, project, summary, readonly } from '../development/helpers.ts'

test('P10: ID order, adjacent movement, undo, redo and reset are separate from task fields', async ({ page }) => {
  const writes = await mount(page)
  const initial = webIds()
  await expectIds(page, initial)
  await expect(page.getByLabel('Mesto opravila web-02', { exact: true })).toHaveText('2')
  await expect(page.getByRole('button', { name: 'Premakni web-01 gor', exact: true })).toBeDisabled()

  await click(page, 'Premakni web-02 gor')
  await expectIds(page, ['web-02', 'web-01', ...initial.slice(2)])
  await expect(page.getByLabel('Mesto opravila web-02', { exact: true })).toHaveText('1')
  await expect(page.getByRole('status', { name: 'Zgodovina vrstnega reda' })).toHaveText('Razveljavitve: 1. Ponovitve: 0.')
  await expect(page.locator('[data-task-id="web-03"]')).toContainText('Končano')
  await summary(page, [4, 2, 2])

  await click(page, 'Razveljavi premik')
  await expectIds(page, initial)
  await expect(page.getByRole('button', { name: 'Premakni web-01 gor', exact: true })).toBeDisabled()
  await expect(page.getByRole('status', { name: 'Zgodovina vrstnega reda' })).toHaveText('Razveljavitve: 0. Ponovitve: 1.')
  await click(page, 'Ponovi premik')
  await expectIds(page, ['web-02', 'web-01', ...initial.slice(2)])
  await click(page, 'Začetni vrstni red')
  await expectIds(page, initial)
  await expect(page.getByRole('button', { name: 'Začetni vrstni red', exact: true })).toBeDisabled()
  await click(page, 'Razveljavi premik')
  await expectIds(page, ['web-02', 'web-01', ...initial.slice(2)])
  await click(page, 'Ponovi premik')
  await expectIds(page, initial)
  expect(writes).toEqual([])
})

test('P10: global neighbors in the board and history survive view and detail changes', async ({ page }) => {
  await mount(page)
  await summary(page, [4, 2, 2])
  await board(page)
  await click(page, 'Premakni web-02 gor')
  await expect(page.getByLabel('Mesto opravila web-02', { exact: true })).toHaveText('1')
  await expect(page.getByLabel('Mesto opravila web-01', { exact: true })).toHaveText('2')
  await expect(page.getByRole('region', { name: 'Tabla opravil' }).locator('[data-task-id]')).toHaveCount(8)
  await page.locator('[data-task-id="web-02"] a.board-card').click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: 'Zapri podrobnosti' }).click()
  await table(page)
  await expectIds(page, ['web-02', 'web-01', ...webIds().slice(2)])
  await expect(page.getByRole('status', { name: 'Zgodovina vrstnega reda' })).toHaveText('Razveljavitve: 1. Ponovitve: 0.')
  await summary(page, [4, 2, 2])
})

test('P10: only the most recent twenty undo snapshots are retained', async ({ page }) => {
  await mount(page)
  for (let index = 0; index < 11; index += 1) {
    await click(page, 'Premakni web-02 gor')
    await click(page, 'Premakni web-02 dol')
  }
  await expect(page.getByRole('status', { name: 'Zgodovina vrstnega reda' })).toHaveText('Razveljavitve: 20. Ponovitve: 0.')
  for (let index = 0; index < 20; index += 1) await click(page, 'Razveljavi premik')
  await expectIds(page, webIds())
  await expect(page.getByRole('button', { name: 'Razveljavi premik', exact: true })).toBeDisabled()
  await expect(page.getByRole('status', { name: 'Zgodovina vrstnega reda' })).toHaveText('Razveljavitve: 0. Ponovitve: 20.')
  for (let index = 0; index < 20; index += 1) await click(page, 'Ponovi premik')
  await expectIds(page, webIds())
  await expect(page.getByRole('status', { name: 'Zgodovina vrstnega reda' })).toHaveText('Razveljavitve: 20. Ponovitve: 0.')
})

test('P10: project change and reload reinitialize the order', async ({ page }) => {
  await mount(page)
  await click(page, 'Premakni web-02 gor')
  await project(page, 'launch')
  await project(page, 'web')
  await expectIds(page, webIds())
  await click(page, 'Premakni web-02 gor')
  await page.reload()
  await expectIds(page, webIds())
})

