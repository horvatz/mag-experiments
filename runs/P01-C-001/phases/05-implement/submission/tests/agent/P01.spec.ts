import { expect, test, type Page } from '@playwright/test'
import type { Task } from '../../shared/types.ts'
const labels = { todo: 'Pripravljeno', in_progress: 'V delu', done: 'Končano' }
async function edit(page: Page, id = 'web-02') {
  await page.goto(`/#/projects/web/tasks/${id}`)
  await page.getByRole('button', { name: 'Uredi', exact: true }).click()
}
test.beforeEach(async ({ request }) => { await request.post('/__test/reset') })
test('A01: isolation, transitions, views, persistence and identity', async ({ page, request }) => {
  const before = (await (await request.get('/__test/state')).json()).tasks as Task[]
  await edit(page)
  const title = page.getByRole('textbox', { name: 'Naslov', exact: true })
  const status = page.getByRole('combobox', { name: 'Stanje', exact: true })
  await expect(title).toHaveValue('Pregled vsebine')
  for (const next of ['in_progress', 'todo', 'done', 'in_progress', 'done', 'todo', 'todo'] as const) {
    await title.fill('Nov  naslov')
    await status.selectOption(next)
    const stored = await (await request.get('/api/tasks/web-02')).json()
    await expect(page.locator('tr[data-task-id="web-02"]')).toContainText(stored.title)
    await page.getByRole('button', { name: 'Shrani', exact: true }).click()
    await expect(title).toBeHidden()
    await expect(page.getByRole('dialog').getByRole('heading', { name: 'Nov  naslov' })).toBeVisible()
    await expect(page.locator('tr[data-task-id="web-02"]')).toContainText(labels[next])
    await page.getByRole('button', { name: 'Uredi', exact: true }).click()
  }
  await page.getByRole('button', { name: 'Prekliči', exact: true }).click()
  const after = (await (await request.get('/__test/state')).json()).tasks as Task[]
  expect(after).toEqual(before.map(t => t.id === 'web-02' ? { ...t, title: 'Nov  naslov', status: 'todo' } : t))
  await page.getByRole('button', { name: 'Zapri podrobnosti' }).click()
  await page.getByRole('button', { name: 'Tabla', exact: true }).click()
  await expect(page.locator('.board-todo [data-task-id="web-02"]')).toContainText('Nov  naslov')
  const counts = page.getByLabel('Pregled stanj opravil').locator('strong')
  await expect(counts).toHaveText(['1', '1', '1'])
  await page.reload()
  await expect(page.locator('[data-task-id="web-02"]')).toContainText('Nov  naslov')
  await page.getByRole('navigation').getByRole('link', { name: 'Jesenska kampanja' }).click()
  await expect(page.locator('[data-task-id="launch-01"]')).toBeVisible()
})
test('A02: whitespace, validation, cancel and clean next form', async ({ page, request }) => {
  await edit(page)
  const title = page.getByRole('textbox', { name: 'Naslov', exact: true })
  await title.fill(' \t\n\r')
  await page.getByRole('button', { name: 'Shrani', exact: true }).click()
  await expect(title).toHaveAttribute('aria-invalid', 'true')
  await expect(title).toHaveAttribute('aria-describedby', 'title-error')
  expect((await (await request.get('/__test/state')).json()).saveRequests).toBe(0)
  await title.fill('Veljavno')
  await expect(page.getByRole('alert')).toBeHidden()
  await page.getByRole('button', { name: 'Prekliči', exact: true }).click()
  await page.getByRole('button', { name: 'Uredi', exact: true }).click()
  await expect(title).toHaveValue('Pregled vsebine')
  await title.fill(' \t\nA  B\nC\u00a0\t ')
  await page.getByRole('button', { name: 'Shrani', exact: true }).click()
  await expect(title).toBeHidden()
  expect((await (await request.get('/api/tasks/web-02')).json()).title).toBe('A  B\nC\u00a0')
  await edit(page, 'web-01')
  await expect(title).not.toHaveValue('A  B\nC\u00a0')
  await expect(page.getByRole('alert')).toBeHidden()
  await title.fill('\u00a0')
  await page.getByRole('button', { name: 'Shrani', exact: true }).click()
  await expect(title).toBeHidden()
  expect((await (await request.get('/api/tasks/web-01')).json()).title).toBe('\u00a0')
})
test('A03: held rejection, single request and retry', async ({ page, request }) => {
  const before = (await (await request.get('/__test/state')).json()).tasks
  await edit(page)
  const title = page.getByRole('textbox', { name: 'Naslov', exact: true })
  const status = page.getByRole('combobox', { name: 'Stanje', exact: true })
  await title.fill('Ponovljeno')
  await status.selectOption('done')
  await request.post('/__test/next-save', { data: { mode: 'hold' } })
  await page.getByRole('button', { name: 'Shrani', exact: true }).evaluate((button: HTMLButtonElement) => { button.click(); button.click(); button.click() })
  await expect(page.getByRole('dialog').getByRole('status')).toBeVisible()
  for (const control of [title, status, page.getByRole('button', { name: 'Shrani', exact: true }), page.getByRole('button', { name: 'Prekliči', exact: true })]) await expect(control).toBeDisabled()
  const held = await (await request.get('/__test/state')).json()
  expect(held).toMatchObject({ tasks: before, saveRequests: 1, pending: 1 })
  await expect(page.locator('tr[data-task-id="web-02"]')).toContainText('Pregled vsebine')
  await request.post('/__test/release', { data: { outcome: 'reject' } })
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(title).toHaveValue('Ponovljeno')
  await expect(title).toBeEnabled()
  expect((await (await request.get('/__test/state')).json()).tasks).toEqual(before)
  await page.getByRole('button', { name: 'Shrani', exact: true }).click()
  await expect(title).toBeHidden()
  await expect(page.getByRole('alert')).toBeHidden()
  await expect(page.locator('tr[data-task-id="web-02"]')).toContainText('Končano')
})
test('A04: mobile form remains usable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await edit(page)
  const title = page.getByRole('textbox', { name: 'Naslov', exact: true })
  await title.focus()
  await expect(title).toBeFocused()
  const box = await title.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(390)
  await page.getByRole('button', { name: 'Prekliči', exact: true }).click()
  await expect(title).toBeHidden()
})
